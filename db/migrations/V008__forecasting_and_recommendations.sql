-- =============================================================================
-- V008 — Forecasting module: ML model registry with versioning, holdout
--        benchmarks (KPI-02), forecast runs and values, explainable
--        replenishment recommendations (US07, US09, US10, US13, NFR08).
-- =============================================================================

CREATE TYPE forecast.forecast_method       AS ENUM ('zero', 'ma3', 'ses', 'croston', 'sba', 'fasttree');
CREATE TYPE forecast.model_status          AS ENUM ('training', 'candidate', 'active', 'retired', 'rejected');
CREATE TYPE forecast.run_status            AS ENUM ('running', 'succeeded', 'failed');
CREATE TYPE forecast.recommendation_kind   AS ENUM ('transfer', 'purchase');
CREATE TYPE forecast.recommendation_status AS ENUM ('open', 'accepted', 'overridden', 'rejected', 'expired');
COMMENT ON TYPE forecast.forecast_method IS 'fasttree = ML.NET FastTree regressor; the others are the five statistical benchmarks of KPI-02.';

-- ---------------------------------------------------------------------------
-- Model registry (automatic retraining, versions, candidate check before swap)
-- ---------------------------------------------------------------------------
CREATE TABLE forecast.ml_model_version (
    id                 integer                   GENERATED BY DEFAULT AS IDENTITY,
    algorithm          forecast.forecast_method  NOT NULL,
    version_label      varchar(30)               NOT NULL,
    demand_class_code  varchar(15),
    status             forecast.model_status     NOT NULL DEFAULT 'training',
    training_from      date                      NOT NULL,
    training_to        date                      NOT NULL,
    holdout_from       date                      NOT NULL,
    holdout_to         date                      NOT NULL,
    rmsse              numeric(8,4),
    mase               numeric(8,4),
    mae                numeric(12,4),
    rmse               numeric(12,4),
    hyperparameters    jsonb                     NOT NULL DEFAULT '{}'::jsonb,
    artifact_uri       varchar(500),
    artifact_sha256    char(64),
    trained_at         timestamptz,
    promoted_at        timestamptz,
    retired_at         timestamptz,
    created_at         timestamptz               NOT NULL DEFAULT now(),
    CONSTRAINT pk_ml_model_version PRIMARY KEY (id),
    CONSTRAINT uq_ml_model_version_label UNIQUE (algorithm, version_label),
    CONSTRAINT fk_ml_model_version_class FOREIGN KEY (demand_class_code) REFERENCES ref.demand_class (code),
    CONSTRAINT ck_ml_model_version_label CHECK (version_label ~ '^v\d+\.\d+(\.\d+)?$'),
    CONSTRAINT ck_ml_model_version_training CHECK (training_to > training_from),
    -- Risk R1 / application text: evaluation only on LATER periods excluded from training.
    CONSTRAINT ck_ml_model_version_chronological_holdout CHECK (holdout_from > training_to AND holdout_to >= holdout_from),
    CONSTRAINT ck_ml_model_version_metrics CHECK (
        (rmsse IS NULL OR rmsse >= 0) AND (mase IS NULL OR mase >= 0) AND (mae IS NULL OR mae >= 0) AND (rmse IS NULL OR rmse >= 0)),
    CONSTRAINT ck_ml_model_version_evaluated CHECK (status IN ('training', 'rejected') OR (rmsse IS NOT NULL AND trained_at IS NOT NULL)),
    CONSTRAINT ck_ml_model_version_artifact CHECK (algorithm <> 'fasttree' OR status = 'training' OR artifact_uri IS NOT NULL),
    CONSTRAINT ck_ml_model_version_sha CHECK (artifact_sha256 IS NULL OR artifact_sha256 ~ '^[0-9a-f]{64}$'),
    -- jsonb is used ONLY for algorithm-specific hyper-parameters (different key sets per
    -- algorithm, read/written as a whole, never filtered) and must be a JSON object.
    CONSTRAINT ck_ml_model_version_hyperparameters CHECK (jsonb_typeof(hyperparameters) = 'object'),
    CONSTRAINT ck_ml_model_version_active CHECK (status <> 'active' OR promoted_at IS NOT NULL)
);
-- Exactly one active model per scope (demand class or "all classes").
CREATE UNIQUE INDEX uq_ml_model_version_one_active
    ON forecast.ml_model_version ((coalesce(demand_class_code, '*'))) WHERE status = 'active';
CREATE INDEX ix_ml_model_version_class ON forecast.ml_model_version (demand_class_code);
COMMENT ON TABLE  forecast.ml_model_version IS 'Versioned ML / benchmark models. A candidate is promoted to active only if it beats the best benchmark (forecast.promote_model).';
COMMENT ON COLUMN forecast.ml_model_version.hyperparameters IS 'Algorithm-specific settings as a JSON object, e.g. {"numberOfTrees":200,"numberOfLeaves":31,"learningRate":0.1}.';
COMMENT ON COLUMN forecast.ml_model_version.artifact_uri IS 'Location of the serialised ML.NET model (.zip) in Azure Blob Storage.';

CREATE TABLE forecast.benchmark_result (
    model_version_id   integer                   NOT NULL,
    method             forecast.forecast_method  NOT NULL,
    demand_class_code  varchar(15)               NOT NULL,
    series_count       integer                   NOT NULL,
    rmsse              numeric(8,4)              NOT NULL,
    mase               numeric(8,4)              NOT NULL,
    CONSTRAINT pk_benchmark_result PRIMARY KEY (model_version_id, method, demand_class_code),
    CONSTRAINT fk_benchmark_result_model FOREIGN KEY (model_version_id) REFERENCES forecast.ml_model_version (id) ON DELETE CASCADE,
    CONSTRAINT fk_benchmark_result_class FOREIGN KEY (demand_class_code) REFERENCES ref.demand_class (code),
    CONSTRAINT ck_benchmark_result_series CHECK (series_count > 0),
    CONSTRAINT ck_benchmark_result_metrics CHECK (rmsse >= 0 AND mase >= 0)
);
CREATE INDEX ix_benchmark_result_class ON forecast.benchmark_result (demand_class_code);
COMMENT ON TABLE forecast.benchmark_result IS 'Holdout accuracy of a candidate model and of the 5 benchmarks per demand class (KPI-02: ML must have >= 10% lower RMSSE).';

-- ---------------------------------------------------------------------------
-- Forecast runs and weekly forecast values
-- ---------------------------------------------------------------------------
CREATE TABLE forecast.forecast_run (
    id                bigint               GENERATED BY DEFAULT AS IDENTITY,
    model_version_id  integer              NOT NULL,
    status            forecast.run_status  NOT NULL DEFAULT 'running',
    horizon_weeks     smallint             NOT NULL,
    first_week        date                 NOT NULL,
    triggered_by      varchar(10)          NOT NULL,
    requested_by      uuid,
    started_at        timestamptz          NOT NULL DEFAULT now(),
    finished_at       timestamptz,
    error_message     text,
    CONSTRAINT pk_forecast_run PRIMARY KEY (id),
    CONSTRAINT fk_forecast_run_model FOREIGN KEY (model_version_id) REFERENCES forecast.ml_model_version (id),
    CONSTRAINT fk_forecast_run_user  FOREIGN KEY (requested_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_forecast_run_horizon CHECK (horizon_weeks BETWEEN 4 AND 12),
    CONSTRAINT ck_forecast_run_first_week_monday CHECK (extract(isodow FROM first_week) = 1),
    CONSTRAINT ck_forecast_run_trigger CHECK (triggered_by IN ('scheduler', 'user')),
    CONSTRAINT ck_forecast_run_user CHECK (triggered_by = 'scheduler' OR requested_by IS NOT NULL),
    CONSTRAINT ck_forecast_run_finished CHECK ((status = 'running') = (finished_at IS NULL)),
    CONSTRAINT ck_forecast_run_timeline CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_forecast_run_error CHECK ((status = 'failed') = (error_message IS NOT NULL))
);
CREATE INDEX ix_forecast_run_model ON forecast.forecast_run (model_version_id);
CREATE INDEX ix_forecast_run_user  ON forecast.forecast_run (requested_by);
CREATE INDEX ix_forecast_run_latest ON forecast.forecast_run (started_at DESC) WHERE status = 'succeeded';
COMMENT ON TABLE forecast.forecast_run IS 'One execution of the forecasting pipeline (Quartz.NET weekly or user-triggered, horizon 4-12 weeks).';

CREATE TABLE forecast.demand_forecast (
    forecast_run_id  bigint         NOT NULL,
    warehouse_id     smallint       NOT NULL,
    part_id          bigint         NOT NULL,
    week_start       date           NOT NULL,
    forecast_qty     numeric(12,3)  NOT NULL,
    CONSTRAINT pk_demand_forecast PRIMARY KEY (forecast_run_id, warehouse_id, part_id, week_start),
    CONSTRAINT fk_demand_forecast_run FOREIGN KEY (forecast_run_id) REFERENCES forecast.forecast_run (id) ON DELETE CASCADE,
    CONSTRAINT fk_demand_forecast_warehouse_part FOREIGN KEY (warehouse_id, part_id)
        REFERENCES inventory.warehouse_part (warehouse_id, part_id),
    CONSTRAINT ck_demand_forecast_qty CHECK (forecast_qty >= 0),
    CONSTRAINT ck_demand_forecast_monday CHECK (extract(isodow FROM week_start) = 1)
);
-- "Forecast of this SKU at this hub" look-ups across runs (explain view, accuracy).
CREATE INDEX ix_demand_forecast_part_wh_week ON forecast.demand_forecast (part_id, warehouse_id, week_start);
COMMENT ON TABLE forecast.demand_forecast IS 'Weekly forecast quantity per run, warehouse and part (ternary relationship run x warehouse x part, plus week).';

-- ---------------------------------------------------------------------------
-- Explainable recommendations (NFR08: every proposal carries its drivers)
-- ---------------------------------------------------------------------------
CREATE TABLE forecast.recommendation (
    id                      bigint                          GENERATED BY DEFAULT AS IDENTITY,
    forecast_run_id         bigint                          NOT NULL,
    kind                    forecast.recommendation_kind    NOT NULL,
    warehouse_id            smallint                        NOT NULL,
    part_id                 bigint                          NOT NULL,
    donor_warehouse_id      smallint,
    supplier_id             integer,
    -- NFR08 decomposition (a)-(d) and the stock position (UC01 step 5)
    base_demand_qty         numeric(12,3)                   NOT NULL,
    maintenance_demand_qty  numeric(12,3)                   NOT NULL,
    lead_time_buffer_qty    numeric(12,3)                   NOT NULL,
    safety_stock_qty        numeric(12,3)                   NOT NULL,
    available_qty           numeric(12,3)                   NOT NULL,
    in_transit_qty          numeric(12,3)                   NOT NULL,
    net_position_qty        numeric(12,3)                   NOT NULL,
    recommended_qty         numeric(12,3)                   NOT NULL,
    estimated_cost_eur      numeric(12,2)                   NOT NULL,
    alternative_cost_eur    numeric(12,2),
    status                  forecast.recommendation_status  NOT NULL DEFAULT 'open',
    final_qty               numeric(12,3),
    decided_by              uuid,
    decided_at              timestamptz,
    decision_reason         varchar(300),
    transfer_order_id       bigint,
    purchase_order_id       bigint,
    created_at              timestamptz                     NOT NULL DEFAULT now(),
    CONSTRAINT pk_recommendation PRIMARY KEY (id),
    CONSTRAINT fk_recommendation_run         FOREIGN KEY (forecast_run_id) REFERENCES forecast.forecast_run (id) ON DELETE CASCADE,
    CONSTRAINT fk_recommendation_wh_part     FOREIGN KEY (warehouse_id, part_id) REFERENCES inventory.warehouse_part (warehouse_id, part_id),
    CONSTRAINT fk_recommendation_donor       FOREIGN KEY (donor_warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT fk_recommendation_supplier    FOREIGN KEY (supplier_id) REFERENCES catalog.supplier (id),
    CONSTRAINT fk_recommendation_decided_by  FOREIGN KEY (decided_by) REFERENCES iam.app_user (id),
    CONSTRAINT fk_recommendation_transfer    FOREIGN KEY (transfer_order_id) REFERENCES inventory.transfer_order (id) ON DELETE SET NULL,
    CONSTRAINT fk_recommendation_po          FOREIGN KEY (purchase_order_id) REFERENCES procurement.purchase_order (id) ON DELETE SET NULL,
    CONSTRAINT ck_recommendation_drivers CHECK (
        base_demand_qty >= 0 AND maintenance_demand_qty >= 0 AND lead_time_buffer_qty >= 0
        AND safety_stock_qty >= 0 AND available_qty >= 0 AND in_transit_qty >= 0),
    -- The explanation must add up (NFR08): Net = Available + InTransit - (a + b + c + d).
    CONSTRAINT ck_recommendation_net_position CHECK (
        net_position_qty = available_qty + in_transit_qty
                           - (base_demand_qty + maintenance_demand_qty + lead_time_buffer_qty + safety_stock_qty)),
    CONSTRAINT ck_recommendation_qty  CHECK (recommended_qty > 0),
    CONSTRAINT ck_recommendation_cost CHECK (estimated_cost_eur >= 0 AND (alternative_cost_eur IS NULL OR alternative_cost_eur >= 0)),
    CONSTRAINT ck_recommendation_kind_transfer CHECK (
        kind <> 'transfer' OR (donor_warehouse_id IS NOT NULL AND supplier_id IS NULL AND donor_warehouse_id <> warehouse_id)),
    CONSTRAINT ck_recommendation_kind_purchase CHECK (
        kind <> 'purchase' OR (supplier_id IS NOT NULL AND donor_warehouse_id IS NULL)),
    CONSTRAINT ck_recommendation_decided CHECK (
        (status IN ('open', 'expired')) = (decided_at IS NULL)),
    CONSTRAINT ck_recommendation_final_qty CHECK (
        status NOT IN ('accepted', 'overridden') OR (final_qty > 0 AND decided_by IS NOT NULL)),
    CONSTRAINT ck_recommendation_accepted CHECK (status <> 'accepted' OR final_qty = recommended_qty),
    CONSTRAINT ck_recommendation_override CHECK (
        status NOT IN ('overridden', 'rejected') OR decision_reason IS NOT NULL),
    CONSTRAINT ck_recommendation_override_qty CHECK (status <> 'overridden' OR final_qty <> recommended_qty)
);
CREATE INDEX ix_recommendation_run ON forecast.recommendation (forecast_run_id);
CREATE INDEX ix_recommendation_wh_part ON forecast.recommendation (warehouse_id, part_id);
CREATE INDEX ix_recommendation_open ON forecast.recommendation (kind, created_at) WHERE status = 'open';
CREATE INDEX ix_recommendation_donor ON forecast.recommendation (donor_warehouse_id) WHERE donor_warehouse_id IS NOT NULL;
CREATE INDEX ix_recommendation_supplier ON forecast.recommendation (supplier_id) WHERE supplier_id IS NOT NULL;
CREATE INDEX ix_recommendation_decided_by ON forecast.recommendation (decided_by);
CREATE INDEX ix_recommendation_transfer ON forecast.recommendation (transfer_order_id) WHERE transfer_order_id IS NOT NULL;
CREATE INDEX ix_recommendation_po ON forecast.recommendation (purchase_order_id) WHERE purchase_order_id IS NOT NULL;
COMMENT ON TABLE  forecast.recommendation IS 'Explainable transfer / purchase proposal. Stores every driver of the calculation (NFR08) and the human decision (KPI-04).';
COMMENT ON COLUMN forecast.recommendation.alternative_cost_eur IS 'Cost of the alternative (e.g. emergency supplier order EUR 280 vs. transfer EUR 45, UC01 step 9).';
