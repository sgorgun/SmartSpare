-- =============================================================================
-- V010 — Data layers for CSV import (BA C.2 data migration, US03 CSV upload):
--   raw     : rows exactly as in the file (text), + file metadata and SHA-256
--   staging : typed, normalised, validated rows + validation errors
--   core    : catalog.part / inventory.stock_movement (loaded by functions in V013)
-- =============================================================================

CREATE TYPE raw.import_source AS ENUM ('part_catalog', 'demand_history');
CREATE TYPE raw.import_status AS ENUM ('uploaded', 'validated', 'loaded', 'failed');

CREATE TABLE raw.import_batch (
    id            bigint             GENERATED BY DEFAULT AS IDENTITY,
    source        raw.import_source  NOT NULL,
    file_name     varchar(255)       NOT NULL,
    file_sha256   char(64)           NOT NULL,
    status        raw.import_status  NOT NULL DEFAULT 'uploaded',
    total_rows    integer            NOT NULL DEFAULT 0,
    valid_rows    integer,
    error_rows    integer,
    loaded_rows   integer,
    uploaded_by   uuid,
    uploaded_at   timestamptz        NOT NULL DEFAULT now(),
    processed_at  timestamptz,
    message       text,
    CONSTRAINT pk_import_batch PRIMARY KEY (id),
    -- Deduplication: the same file content cannot be imported twice.
    CONSTRAINT uq_import_batch_file UNIQUE (source, file_sha256),
    CONSTRAINT fk_import_batch_user FOREIGN KEY (uploaded_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_import_batch_sha CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_batch_counts CHECK (
        total_rows >= 0 AND coalesce(valid_rows, 0) + coalesce(error_rows, 0) <= total_rows
        AND coalesce(loaded_rows, 0) <= coalesce(valid_rows, total_rows)),
    CONSTRAINT ck_import_batch_processed CHECK (status = 'uploaded' OR processed_at IS NOT NULL)
);
CREATE INDEX ix_import_batch_user ON raw.import_batch (uploaded_by);
CREATE INDEX ix_import_batch_status ON raw.import_batch (status, uploaded_at DESC);
COMMENT ON TABLE raw.import_batch IS 'One uploaded CSV file: source, SHA-256 (duplicate-file protection), processing status and row counts (load monitoring).';

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT fk_stock_movement_import_batch FOREIGN KEY (import_batch_id) REFERENCES raw.import_batch (id);

-- Raw rows: everything as text, exactly as received (no data loss on bad input).
CREATE TABLE raw.part_catalog_row (
    import_batch_id  bigint   NOT NULL,
    line_no          integer  NOT NULL,
    brand_code       text,
    oem_part_number  text,
    description      text,
    category_code    text,
    uom_code         text,
    weight_kg        text,
    unit_cost        text,
    condition_based  text,
    CONSTRAINT pk_part_catalog_row PRIMARY KEY (import_batch_id, line_no),
    CONSTRAINT fk_part_catalog_row_batch FOREIGN KEY (import_batch_id) REFERENCES raw.import_batch (id) ON DELETE CASCADE,
    CONSTRAINT ck_part_catalog_row_line CHECK (line_no > 0)
);
COMMENT ON TABLE raw.part_catalog_row IS 'Raw layer: part catalogue CSV rows as text (columns: brand, oem_part_number, description, category, uom, weight_kg, unit_cost, condition_based).';

CREATE TABLE raw.demand_history_row (
    import_batch_id  bigint   NOT NULL,
    line_no          integer  NOT NULL,
    doc_date         text,
    warehouse_code   text,
    brand_code       text,
    oem_part_number  text,
    quantity         text,
    doc_ref          text,
    CONSTRAINT pk_demand_history_row PRIMARY KEY (import_batch_id, line_no),
    CONSTRAINT fk_demand_history_row_batch FOREIGN KEY (import_batch_id) REFERENCES raw.import_batch (id) ON DELETE CASCADE,
    CONSTRAINT ck_demand_history_row_line CHECK (line_no > 0)
);
COMMENT ON TABLE raw.demand_history_row IS 'Raw layer: historical demand (ERP sales/service issues) CSV rows as text.';

-- Staging: typed + normalised. Invalid rows keep is_valid = false.
CREATE TABLE staging.part_catalog (
    import_batch_id     bigint         NOT NULL,
    line_no             integer        NOT NULL,
    brand_id            smallint,
    oem_part_number     varchar(40),
    description         varchar(300),
    category_id         integer,
    uom_id              smallint,
    weight_kg           numeric(9,3),
    unit_cost           numeric(12,2),
    is_condition_based  boolean,
    is_valid            boolean        NOT NULL,
    CONSTRAINT pk_staging_part_catalog PRIMARY KEY (import_batch_id, line_no),
    CONSTRAINT fk_staging_part_catalog_raw FOREIGN KEY (import_batch_id, line_no)
        REFERENCES raw.part_catalog_row (import_batch_id, line_no) ON DELETE CASCADE,
    CONSTRAINT ck_staging_part_catalog_valid CHECK (
        NOT is_valid OR (brand_id IS NOT NULL AND oem_part_number IS NOT NULL AND description IS NOT NULL
                         AND category_id IS NOT NULL AND uom_id IS NOT NULL AND unit_cost IS NOT NULL))
);
COMMENT ON TABLE staging.part_catalog IS 'Staging layer: typed and validated part catalogue rows (valid rows are upserted into catalog.part).';

CREATE TABLE staging.demand_history (
    import_batch_id  bigint         NOT NULL,
    line_no          integer        NOT NULL,
    occurred_at      timestamptz,
    warehouse_id     smallint,
    part_id          bigint,
    quantity         numeric(12,3),
    doc_ref          varchar(40),
    row_hash         bytea,
    is_valid         boolean        NOT NULL,
    is_duplicate     boolean        NOT NULL DEFAULT false,
    CONSTRAINT pk_staging_demand_history PRIMARY KEY (import_batch_id, line_no),
    CONSTRAINT fk_staging_demand_history_raw FOREIGN KEY (import_batch_id, line_no)
        REFERENCES raw.demand_history_row (import_batch_id, line_no) ON DELETE CASCADE,
    CONSTRAINT ck_staging_demand_history_valid CHECK (
        NOT is_valid OR (occurred_at IS NOT NULL AND warehouse_id IS NOT NULL AND part_id IS NOT NULL
                         AND quantity > 0 AND row_hash IS NOT NULL))
);
-- Cross-batch deduplication of business records (same doc/part/hub/date/qty).
CREATE INDEX ix_staging_demand_history_hash ON staging.demand_history (row_hash) WHERE is_valid AND NOT is_duplicate;
COMMENT ON TABLE  staging.demand_history IS 'Staging layer: typed historical demand rows; duplicates (same row_hash as an earlier loaded row) are flagged, not loaded.';
COMMENT ON COLUMN staging.demand_history.row_hash IS 'SHA-256 of the normalised business key (date|hub|part|doc_ref|qty) for deduplication.';

CREATE TABLE staging.import_error (
    id               bigint        GENERATED BY DEFAULT AS IDENTITY,
    import_batch_id  bigint        NOT NULL,
    line_no          integer       NOT NULL,
    column_name      varchar(40)   NOT NULL,
    error_code       varchar(30)   NOT NULL,
    message          varchar(300)  NOT NULL,
    CONSTRAINT pk_import_error PRIMARY KEY (id),
    CONSTRAINT fk_import_error_batch FOREIGN KEY (import_batch_id) REFERENCES raw.import_batch (id) ON DELETE CASCADE,
    CONSTRAINT ck_import_error_code CHECK (error_code IN ('REQUIRED', 'TYPE', 'RANGE', 'FORMAT', 'UNKNOWN_REF', 'DUPLICATE'))
);
CREATE INDEX ix_import_error_batch ON staging.import_error (import_batch_id, line_no);
COMMENT ON TABLE staging.import_error IS 'Data-quality errors found while validating raw rows (shown to the user after an upload).';

-- Safe casts used by validation (return NULL instead of failing).
CREATE FUNCTION util.try_numeric(p text) RETURNS numeric
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    RETURN replace(btrim(p), ',', '.')::numeric;
EXCEPTION WHEN others THEN
    RETURN NULL;
END $$;

CREATE FUNCTION util.try_date(p text) RETURNS date
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF btrim(p) !~ '^\d{4}-\d{2}-\d{2}$' THEN RETURN NULL; END IF;   -- ISO 8601 only
    RETURN btrim(p)::date;
EXCEPTION WHEN others THEN
    RETURN NULL;
END $$;
COMMENT ON FUNCTION util.try_numeric(text) IS 'Casts text to numeric (accepts decimal comma); NULL if not a number.';
COMMENT ON FUNCTION util.try_date(text) IS 'Casts an ISO-8601 date (YYYY-MM-DD) to date; NULL if invalid.';
