-- =============================================================================
-- V004 — Identity & Access Management: users, roles, brand assignments
-- Passwords: only ASP.NET Core Identity V3 hashes (PBKDF2-HMAC-SHA512,
-- 100,000 iterations, 128-bit salt) are accepted — enforced by a CHECK.
-- =============================================================================

CREATE TABLE iam.app_user (
    id                  uuid          NOT NULL DEFAULT gen_random_uuid(),
    user_name           citext        NOT NULL,
    email               citext        NOT NULL,
    full_name           varchar(150)  NOT NULL,
    phone               varchar(30),
    password_hash       text,
    security_stamp      uuid          NOT NULL DEFAULT gen_random_uuid(),
    is_active           boolean       NOT NULL DEFAULT true,
    failed_login_count  smallint      NOT NULL DEFAULT 0,
    lockout_end         timestamptz,
    home_warehouse_id   smallint,
    last_login_at       timestamptz,
    anonymised_at       timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uq_app_user_user_name UNIQUE (user_name),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT fk_app_user_home_warehouse FOREIGN KEY (home_warehouse_id) REFERENCES inventory.warehouse (id) ON DELETE SET NULL,
    CONSTRAINT ck_app_user_user_name CHECK (user_name ~ '^[a-z0-9._-]{3,50}$'),
    CONSTRAINT ck_app_user_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_app_user_phone CHECK (phone IS NULL OR phone ~ '^\+?[0-9 ()-]{7,20}$'),
    -- Identity V3 format: base64(0x01 | PRF | iterations | salt length | salt | subkey).
    -- Rejects plain text and outdated hashes (MD5 = 32 hex chars, SHA-1 = 40 hex chars).
    CONSTRAINT ck_app_user_password_hash_format CHECK (password_hash IS NULL OR password_hash ~ '^AQAAAA[A-Za-z0-9+/]{76,}={0,2}$'),
    -- An active account must be able to log in; anonymised accounts are inactive.
    CONSTRAINT ck_app_user_active_has_password CHECK (password_hash IS NOT NULL OR NOT is_active),
    CONSTRAINT ck_app_user_anonymised_inactive CHECK (anonymised_at IS NULL OR NOT is_active),
    CONSTRAINT ck_app_user_failed_logins CHECK (failed_login_count BETWEEN 0 AND 100)
);
CREATE INDEX ix_app_user_home_warehouse ON iam.app_user (home_warehouse_id);
CREATE TRIGGER trg_app_user_updated_at BEFORE UPDATE ON iam.app_user
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  iam.app_user IS 'Dealership employees using SmartSpare. Contains personal data (full_name, email, phone): masked for app_read / app_audit.';
COMMENT ON COLUMN iam.app_user.password_hash IS 'ASP.NET Core Identity V3 hash (PBKDF2-HMAC-SHA512, 100k iterations). Plain text is impossible by CHECK.';
COMMENT ON COLUMN iam.app_user.security_stamp IS 'Changes on password/role change; invalidates issued JWT refresh tokens.';
COMMENT ON COLUMN iam.app_user.full_name IS 'PERSONAL DATA (GDPR). Masked by util.mask_name for read-only roles.';
COMMENT ON COLUMN iam.app_user.email IS 'PERSONAL DATA (GDPR). Corporate e-mail; masked by util.mask_email for read-only roles.';
COMMENT ON COLUMN iam.app_user.phone IS 'PERSONAL DATA (GDPR). Masked by util.mask_phone for read-only roles.';
COMMENT ON COLUMN iam.app_user.anonymised_at IS 'Set by iam.anonymise_user() (GDPR Art. 17); the row is kept so audit references stay valid.';

CREATE TABLE iam.role (
    id           smallint      GENERATED BY DEFAULT AS IDENTITY,
    code         varchar(30)   NOT NULL,
    name         varchar(80)   NOT NULL,
    description  text,
    CONSTRAINT pk_role PRIMARY KEY (id),
    CONSTRAINT uq_role_code UNIQUE (code),
    CONSTRAINT ck_role_code CHECK (code ~ '^[A-Z_]{3,30}$')
);
COMMENT ON TABLE iam.role IS 'Application (RBAC) roles from the BA: BRAND_MANAGER, SERVICE_ENGINEER, WAREHOUSE_KEEPER, INVENTORY_PLANNER, SPONSOR, ADMINISTRATOR.';

CREATE TABLE iam.user_role (
    user_id     uuid         NOT NULL,
    role_id     smallint     NOT NULL,
    granted_at  timestamptz  NOT NULL DEFAULT now(),
    granted_by  uuid,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user       FOREIGN KEY (user_id)    REFERENCES iam.app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role       FOREIGN KEY (role_id)    REFERENCES iam.role (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_role_granted_by FOREIGN KEY (granted_by) REFERENCES iam.app_user (id) ON DELETE SET NULL
);
CREATE INDEX ix_user_role_role ON iam.user_role (role_id);
CREATE INDEX ix_user_role_granted_by ON iam.user_role (granted_by);
COMMENT ON TABLE iam.user_role IS 'M:N user <-> role assignment.';

CREATE TABLE iam.user_brand (
    user_id   uuid      NOT NULL,
    brand_id  smallint  NOT NULL,
    CONSTRAINT pk_user_brand PRIMARY KEY (user_id, brand_id),
    CONSTRAINT fk_user_brand_user  FOREIGN KEY (user_id)  REFERENCES iam.app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_brand_brand FOREIGN KEY (brand_id) REFERENCES ref.brand (id) ON DELETE CASCADE
);
CREATE INDEX ix_user_brand_brand ON iam.user_brand (brand_id);
COMMENT ON TABLE iam.user_brand IS 'M:N brand manager <-> brands they are responsible for (e.g. persona Tomas: Claas and Lemken).';

-- Helper used by business functions for authorisation checks inside the DB.
CREATE FUNCTION iam.user_has_role(p_user_id uuid, VARIADIC p_roles text[]) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
        FROM iam.user_role ur
        JOIN iam.role r     ON r.id = ur.role_id
        JOIN iam.app_user u ON u.id = ur.user_id
        WHERE ur.user_id = p_user_id AND u.is_active AND r.code = ANY (p_roles))
$$;
COMMENT ON FUNCTION iam.user_has_role(uuid, text[]) IS 'TRUE if the active user has at least one of the given role codes.';
