-- =============================================================================
-- V006 — Fleet & Maintenance module: customers (pseudonymised), machine models,
--        machines, engine-hour readings, OEM maintenance plans + kits (BOM),
--        service orders (US01, US02, US05, US06, UC02).
-- =============================================================================

CREATE TYPE fleet.machine_status       AS ENUM ('active', 'inactive', 'decommissioned');
CREATE TYPE fleet.reading_source       AS ENUM ('manual', 'telematics', 'service_visit', 'import');
CREATE TYPE fleet.service_order_status AS ENUM ('draft', 'parts_reserved', 'in_progress', 'completed', 'cancelled');

-- ---------------------------------------------------------------------------
-- Customers: pseudonymised (BA 2.8 — no personal data of farm owners stored)
-- ---------------------------------------------------------------------------
CREATE TABLE fleet.customer (
    id                   bigint        GENERATED BY DEFAULT AS IDENTITY,
    customer_code        varchar(12)   NOT NULL,
    erp_ref_hash         bytea,
    region_warehouse_id  smallint      NOT NULL,
    farm_size_ha         numeric(8,1),
    is_active            boolean       NOT NULL DEFAULT true,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_customer PRIMARY KEY (id),
    CONSTRAINT uq_customer_code UNIQUE (customer_code),
    CONSTRAINT uq_customer_erp_ref_hash UNIQUE (erp_ref_hash),
    CONSTRAINT fk_customer_region_warehouse FOREIGN KEY (region_warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT ck_customer_code CHECK (customer_code ~ '^CUST-\d{6}$'),
    CONSTRAINT ck_customer_erp_ref_hash CHECK (erp_ref_hash IS NULL OR length(erp_ref_hash) = 32),
    CONSTRAINT ck_customer_farm_size CHECK (farm_size_ha IS NULL OR farm_size_ha > 0)
);
CREATE INDEX ix_customer_region_warehouse ON fleet.customer (region_warehouse_id);
COMMENT ON TABLE  fleet.customer IS 'Machine owner (farm). Pseudonymised: only a code and an HMAC of the ERP id are stored, no names or contacts.';
COMMENT ON COLUMN fleet.customer.erp_ref_hash IS 'HMAC-SHA256 of the ERP customer id (util.pseudonymise); allows matching re-imports without storing the id.';

-- ---------------------------------------------------------------------------
-- Machine models and machines (US01)
-- ---------------------------------------------------------------------------
CREATE TABLE fleet.machine_model (
    id               integer      GENERATED BY DEFAULT AS IDENTITY,
    brand_id         smallint     NOT NULL,
    machine_type_id  smallint     NOT NULL,
    model_name       varchar(80)  NOT NULL,
    CONSTRAINT pk_machine_model PRIMARY KEY (id),
    CONSTRAINT uq_machine_model_brand_name UNIQUE (brand_id, model_name),
    CONSTRAINT fk_machine_model_brand FOREIGN KEY (brand_id) REFERENCES ref.brand (id),
    CONSTRAINT fk_machine_model_type  FOREIGN KEY (machine_type_id) REFERENCES ref.machine_type (id)
);
CREATE INDEX ix_machine_model_type ON fleet.machine_model (machine_type_id);
COMMENT ON TABLE fleet.machine_model IS 'Machine model, e.g. Claas Lexion 8700, John Deere 6R 150.';

CREATE TABLE fleet.machine (
    id                      bigint                NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    vin                     varchar(20)           NOT NULL,
    model_id                integer               NOT NULL,
    customer_id             bigint                NOT NULL,
    operating_condition_id  smallint              NOT NULL,
    home_warehouse_id       smallint              NOT NULL,
    manufacture_year        smallint              NOT NULL,
    current_engine_hours    numeric(8,1)          NOT NULL DEFAULT 0,
    engine_hours_read_at    timestamptz,
    status                  fleet.machine_status  NOT NULL DEFAULT 'active',
    commissioned_on         date,
    created_at              timestamptz           NOT NULL DEFAULT now(),
    updated_at              timestamptz           NOT NULL DEFAULT now(),
    CONSTRAINT pk_machine PRIMARY KEY (id),
    CONSTRAINT uq_machine_vin UNIQUE (vin),
    CONSTRAINT fk_machine_model     FOREIGN KEY (model_id)    REFERENCES fleet.machine_model (id),
    CONSTRAINT fk_machine_customer  FOREIGN KEY (customer_id) REFERENCES fleet.customer (id),
    CONSTRAINT fk_machine_condition FOREIGN KEY (operating_condition_id) REFERENCES ref.operating_condition (id),
    CONSTRAINT fk_machine_home_wh   FOREIGN KEY (home_warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT ck_machine_vin CHECK (vin ~ '^[A-Z0-9]{8,20}$'),
    CONSTRAINT ck_machine_year CHECK (manufacture_year BETWEEN 1950 AND 2100),
    CONSTRAINT ck_machine_engine_hours CHECK (current_engine_hours >= 0 AND current_engine_hours <= 100000),
    CONSTRAINT ck_machine_commissioned CHECK (commissioned_on IS NULL OR extract(year FROM commissioned_on) >= manufacture_year)
);
CREATE INDEX ix_machine_model     ON fleet.machine (model_id);
CREATE INDEX ix_machine_customer  ON fleet.machine (customer_id);
CREATE INDEX ix_machine_condition ON fleet.machine (operating_condition_id);
CREATE INDEX ix_machine_home_wh_active ON fleet.machine (home_warehouse_id) WHERE status = 'active';
-- Field search by partial VIN / serial on the tablet (UC02 step 1).
CREATE INDEX ix_machine_vin_trgm ON fleet.machine USING gin (vin gin_trgm_ops);
CREATE TRIGGER trg_machine_updated_at BEFORE UPDATE ON fleet.machine
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  fleet.machine IS 'Registered machine (installed base). current_engine_hours is maintained by the engine-hour reading trigger.';
COMMENT ON COLUMN fleet.machine.vin IS 'Vehicle / product identification number (unique).';
COMMENT ON COLUMN fleet.machine.home_warehouse_id IS 'Nearest depot where service kits are reserved.';

CREATE TABLE fleet.engine_hours_reading (
    id             bigint                NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    machine_id     bigint                NOT NULL,
    reading_hours  numeric(8,1)          NOT NULL,
    read_at        timestamptz           NOT NULL,
    source         fleet.reading_source  NOT NULL DEFAULT 'manual',
    recorded_by    uuid,
    created_at     timestamptz           NOT NULL DEFAULT now(),
    CONSTRAINT pk_engine_hours_reading PRIMARY KEY (id),
    CONSTRAINT uq_engine_hours_reading_machine_time UNIQUE (machine_id, read_at),
    CONSTRAINT fk_engine_hours_reading_machine FOREIGN KEY (machine_id) REFERENCES fleet.machine (id) ON DELETE CASCADE,
    CONSTRAINT fk_engine_hours_reading_user FOREIGN KEY (recorded_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_engine_hours_reading_hours CHECK (reading_hours >= 0 AND reading_hours <= 100000),
    CONSTRAINT ck_engine_hours_reading_not_future CHECK (read_at <= created_at + interval '5 minutes')
);
CREATE INDEX ix_engine_hours_reading_user ON fleet.engine_hours_reading (recorded_by);
COMMENT ON TABLE fleet.engine_hours_reading IS 'Odometer history (US05). Monotonic and physically plausible readings are enforced by trigger.';
COMMENT ON COLUMN fleet.engine_hours_reading.read_at IS 'Time the reading was taken in the field (may be earlier than created_at for offline entry).';

-- ---------------------------------------------------------------------------
-- OEM maintenance plans and service kits (US02)
-- ---------------------------------------------------------------------------
CREATE TABLE fleet.maintenance_plan (
    id              integer       GENERATED BY DEFAULT AS IDENTITY,
    model_id        integer       NOT NULL,
    interval_hours  integer       NOT NULL,
    name            varchar(120)  NOT NULL,
    is_active       boolean       NOT NULL DEFAULT true,
    CONSTRAINT pk_maintenance_plan PRIMARY KEY (id),
    CONSTRAINT uq_maintenance_plan_model_interval UNIQUE (model_id, interval_hours),
    CONSTRAINT fk_maintenance_plan_model FOREIGN KEY (model_id) REFERENCES fleet.machine_model (id) ON DELETE CASCADE,
    CONSTRAINT ck_maintenance_plan_interval CHECK (interval_hours BETWEEN 10 AND 20000)
);
COMMENT ON TABLE  fleet.maintenance_plan IS 'OEM service interval of a model (e.g. 500 h engine oil service). The effective interval = interval_hours x operating_condition.interval_factor.';

CREATE TABLE fleet.maintenance_plan_part (
    maintenance_plan_id  integer        NOT NULL,
    part_id              bigint         NOT NULL,
    quantity             numeric(12,3)  NOT NULL,
    CONSTRAINT pk_maintenance_plan_part PRIMARY KEY (maintenance_plan_id, part_id),
    CONSTRAINT fk_maintenance_plan_part_plan FOREIGN KEY (maintenance_plan_id) REFERENCES fleet.maintenance_plan (id) ON DELETE CASCADE,
    CONSTRAINT fk_maintenance_plan_part_part FOREIGN KEY (part_id) REFERENCES catalog.part (id),
    CONSTRAINT ck_maintenance_plan_part_qty CHECK (quantity > 0)
);
CREATE INDEX ix_maintenance_plan_part_part ON fleet.maintenance_plan_part (part_id);
COMMENT ON TABLE fleet.maintenance_plan_part IS 'Service kit / bill of materials of a maintenance plan (M:N plan <-> part with quantity).';

-- ---------------------------------------------------------------------------
-- Service orders (US06)
-- ---------------------------------------------------------------------------
CREATE TABLE fleet.service_order (
    id                      bigint                      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    number                  varchar(20)                 NOT NULL,
    machine_id              bigint                      NOT NULL,
    maintenance_plan_id     integer,
    warehouse_id            smallint                    NOT NULL,
    status                  fleet.service_order_status  NOT NULL DEFAULT 'draft',
    due_engine_hours        numeric(8,1),
    trigger_engine_hours    numeric(8,1),
    completed_engine_hours  numeric(8,1),
    created_by              uuid,
    created_at              timestamptz                 NOT NULL DEFAULT now(),
    completed_at            timestamptz,
    cancel_reason           varchar(300),
    updated_at              timestamptz                 NOT NULL DEFAULT now(),
    CONSTRAINT pk_service_order PRIMARY KEY (id),
    CONSTRAINT uq_service_order_number UNIQUE (number),
    CONSTRAINT fk_service_order_machine   FOREIGN KEY (machine_id) REFERENCES fleet.machine (id),
    CONSTRAINT fk_service_order_plan      FOREIGN KEY (maintenance_plan_id) REFERENCES fleet.maintenance_plan (id),
    CONSTRAINT fk_service_order_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT fk_service_order_created_by FOREIGN KEY (created_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_service_order_number CHECK (number ~ '^SO-\d{4}-\d{6}$'),
    CONSTRAINT ck_service_order_planned_due CHECK (maintenance_plan_id IS NULL OR due_engine_hours IS NOT NULL),
    CONSTRAINT ck_service_order_completed CHECK ((status = 'completed') = (completed_at IS NOT NULL AND completed_engine_hours IS NOT NULL)),
    CONSTRAINT ck_service_order_cancel CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL))
);
-- Idempotency: one (non-cancelled) order per machine, plan and due threshold,
-- so repeated engine-hour logging can never draft the same service twice.
CREATE UNIQUE INDEX uq_service_order_machine_plan_due ON fleet.service_order (machine_id, maintenance_plan_id, due_engine_hours)
    WHERE status <> 'cancelled' AND maintenance_plan_id IS NOT NULL;
CREATE INDEX ix_service_order_plan ON fleet.service_order (maintenance_plan_id);
CREATE INDEX ix_service_order_open ON fleet.service_order (warehouse_id, status) WHERE status IN ('draft', 'parts_reserved', 'in_progress');
CREATE INDEX ix_service_order_created_by ON fleet.service_order (created_by);
CREATE TRIGGER trg_service_order_updated_at BEFORE UPDATE ON fleet.service_order
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  fleet.service_order IS 'Service order (SO-YYYY-NNNNNN). Planned (plan + due hours) or unplanned repair (plan NULL). Completed orders form the maintenance history.';
COMMENT ON COLUMN fleet.service_order.due_engine_hours IS 'Engine-hour threshold this planned service covers (e.g. 500, 1000, 1500 ...).';

CREATE TABLE fleet.service_order_line (
    id                bigint         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    service_order_id  bigint         NOT NULL,
    part_id           bigint         NOT NULL,
    qty_required      numeric(12,3)  NOT NULL,
    qty_issued        numeric(12,3)  NOT NULL DEFAULT 0,
    CONSTRAINT pk_service_order_line PRIMARY KEY (id),
    CONSTRAINT uq_service_order_line_part UNIQUE (service_order_id, part_id),
    CONSTRAINT fk_service_order_line_order FOREIGN KEY (service_order_id) REFERENCES fleet.service_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_service_order_line_part  FOREIGN KEY (part_id) REFERENCES catalog.part (id),
    CONSTRAINT ck_service_order_line_required CHECK (qty_required > 0),
    CONSTRAINT ck_service_order_line_issued CHECK (qty_issued >= 0 AND qty_issued <= qty_required)
);
CREATE INDEX ix_service_order_line_part ON fleet.service_order_line (part_id);
COMMENT ON TABLE fleet.service_order_line IS 'Parts required by a service order (copied from the kit, editable for repairs).';

ALTER TABLE inventory.stock_reservation
    ADD CONSTRAINT fk_stock_reservation_service_line FOREIGN KEY (service_order_line_id)
        REFERENCES fleet.service_order_line (id) ON DELETE CASCADE;
ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT fk_stock_movement_service_line FOREIGN KEY (service_order_line_id)
        REFERENCES fleet.service_order_line (id);
