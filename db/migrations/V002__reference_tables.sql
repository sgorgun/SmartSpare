-- V002 — Reference (lookup) tables. Content is loaded by db/seed/R001.
-- Small, rarely changing, business-configurable dictionaries => lookup tables
-- (not enums), so values can be added without a schema change.
-- =============================================================================

CREATE TABLE ref.unit_of_measure (
    id            smallint     GENERATED BY DEFAULT AS IDENTITY,
    code          varchar(10)  NOT NULL,
    name          varchar(50)  NOT NULL,
    is_fractional boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_unit_of_measure PRIMARY KEY (id),
    CONSTRAINT uq_unit_of_measure_code UNIQUE (code),
    CONSTRAINT ck_unit_of_measure_code CHECK (code ~ '^[A-Z0-9]{1,10}$')
);
COMMENT ON TABLE  ref.unit_of_measure IS 'Units of measure of spare parts (PCS, L, KG, M, SET).';
COMMENT ON COLUMN ref.unit_of_measure.is_fractional IS 'TRUE if quantities may be fractional (litres of oil); FALSE for pieces.';

CREATE TABLE ref.brand (
    id           smallint     GENERATED BY DEFAULT AS IDENTITY,
    code         varchar(10)  NOT NULL,
    name         varchar(80)  NOT NULL,
    country_code char(2)      NOT NULL,
    CONSTRAINT pk_brand PRIMARY KEY (id),
    CONSTRAINT uq_brand_code UNIQUE (code),
    CONSTRAINT uq_brand_name UNIQUE (name),
    CONSTRAINT ck_brand_country CHECK (country_code ~ '^[A-Z]{2}$')
);
COMMENT ON TABLE ref.brand IS 'Machinery / OEM brands (Claas, John Deere, Fendt, Massey Ferguson, Lemken, Väderstad ...).';
COMMENT ON COLUMN ref.brand.country_code IS 'ISO 3166-1 alpha-2 country of the manufacturer.';

CREATE TABLE ref.machine_type (
    id    smallint    GENERATED BY DEFAULT AS IDENTITY,
    code  varchar(20) NOT NULL,
    name  varchar(80) NOT NULL,
    CONSTRAINT pk_machine_type PRIMARY KEY (id),
    CONSTRAINT uq_machine_type_code UNIQUE (code)
);
COMMENT ON TABLE ref.machine_type IS 'Machine types: tractor, combine harvester, seeder, sprayer, forage harvester ...';

CREATE TABLE ref.part_category (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    parent_id  integer,
    code       varchar(30)  NOT NULL,
    name       varchar(120) NOT NULL,
    CONSTRAINT pk_part_category PRIMARY KEY (id),
    CONSTRAINT uq_part_category_code UNIQUE (code),
    CONSTRAINT fk_part_category_parent FOREIGN KEY (parent_id) REFERENCES ref.part_category (id) ON DELETE RESTRICT,
    CONSTRAINT ck_part_category_not_self CHECK (parent_id IS DISTINCT FROM id)
);
CREATE INDEX ix_part_category_parent ON ref.part_category (parent_id);
COMMENT ON TABLE ref.part_category IS 'Hierarchical (self-referencing) spare part category tree, e.g. FILTERS > OIL_FILTERS.';
COMMENT ON COLUMN ref.part_category.parent_id IS 'Parent category; NULL for a root category (recursive 1:N relationship).';

CREATE TABLE ref.operating_condition (
    id               smallint      GENERATED BY DEFAULT AS IDENTITY,
    code             varchar(20)   NOT NULL,
    name             varchar(120)  NOT NULL,
    interval_factor  numeric(4,2)  NOT NULL,
    CONSTRAINT pk_operating_condition PRIMARY KEY (id),
    CONSTRAINT uq_operating_condition_code UNIQUE (code),
    CONSTRAINT ck_operating_condition_factor CHECK (interval_factor > 0 AND interval_factor <= 1)
);
COMMENT ON TABLE  ref.operating_condition IS 'Operating conditions that shorten OEM service intervals (finding F5: e.g. non-prescribed oil halves the interval).';
COMMENT ON COLUMN ref.operating_condition.interval_factor IS 'Multiplier applied to the OEM interval: 1.00 = normal, 0.50 = halved.';

CREATE TABLE ref.movement_type (
    code          varchar(20)  NOT NULL,
    name          varchar(80)  NOT NULL,
    balance_sign  smallint     NOT NULL,
    is_demand     boolean      NOT NULL,
    description   text,
    CONSTRAINT pk_movement_type PRIMARY KEY (code),
    CONSTRAINT ck_movement_type_code CHECK (code ~ '^[A-Z_]{3,20}$'),
    CONSTRAINT ck_movement_type_sign CHECK (balance_sign IN (-1, 0, 1)),
    CONSTRAINT ck_movement_type_demand_is_issue CHECK (NOT is_demand OR balance_sign IN (-1, 0))
);
COMMENT ON TABLE  ref.movement_type IS 'Types of stock ledger movements and their effect on the on-hand balance.';
COMMENT ON COLUMN ref.movement_type.balance_sign IS '+1 increases on-hand stock, -1 decreases it, 0 = no physical effect (imported historical demand).';
COMMENT ON COLUMN ref.movement_type.is_demand IS 'TRUE if the movement represents customer/service demand used for forecasting.';

CREATE TABLE ref.demand_class (
    code        varchar(15)   NOT NULL,
    name        varchar(40)   NOT NULL,
    adi_lower   numeric(6,3)  NOT NULL,
    adi_upper   numeric(6,3)  NOT NULL,
    cv2_lower   numeric(6,3)  NOT NULL,
    cv2_upper   numeric(6,3)  NOT NULL,
    description text,
    CONSTRAINT pk_demand_class PRIMARY KEY (code),
    CONSTRAINT ck_demand_class_adi CHECK (adi_lower >= 0 AND adi_upper > adi_lower),
    CONSTRAINT ck_demand_class_cv2 CHECK (cv2_lower >= 0 AND cv2_upper > cv2_lower)
);
COMMENT ON TABLE ref.demand_class IS 'Syntetos-Boylan demand classification by ADI (cut-off 1.32) and CV² (cut-off 0.49); ranges are [lower, upper).';

CREATE TABLE ref.season_phase (
    code  varchar(20)  NOT NULL,
    name  varchar(80)  NOT NULL,
    CONSTRAINT pk_season_phase PRIMARY KEY (code)
);
COMMENT ON TABLE ref.season_phase IS 'Agrotechnical season phases (winter repair, sowing, crop care, harvest, autumn tillage).';

CREATE TABLE ref.agro_calendar_week (
    iso_week          smallint      NOT NULL,
    season_phase_code varchar(20)   NOT NULL,
    seasonal_weight   numeric(4,2)  NOT NULL,
    CONSTRAINT pk_agro_calendar_week PRIMARY KEY (iso_week),
    CONSTRAINT fk_agro_calendar_week_phase FOREIGN KEY (season_phase_code) REFERENCES ref.season_phase (code),
    CONSTRAINT ck_agro_calendar_week_range CHECK (iso_week BETWEEN 1 AND 53),
    CONSTRAINT ck_agro_calendar_week_weight CHECK (seasonal_weight > 0 AND seasonal_weight <= 5)
);
CREATE INDEX ix_agro_calendar_week_phase ON ref.agro_calendar_week (season_phase_code);
COMMENT ON TABLE  ref.agro_calendar_week IS 'ISO week -> season phase mapping for Lithuania; ML feature (EP03, finding F8).';
COMMENT ON COLUMN ref.agro_calendar_week.seasonal_weight IS 'Expert seasonal intensity (1.00 = average week); peaks Feb-Mar and Jul-Sep.';
