-- =============================================================================
-- V005 — Inventory operations: SKU-at-location master data, stock balances,
--        stock movement ledger (partitioned), exceptional demand flags,
--        reservations and inter-warehouse transfers.
-- =============================================================================

-- Workflow states are fixed by application code => PostgreSQL ENUM types
-- (mapped 1:1 to C# enums by Npgsql: NpgsqlDataSourceBuilder.MapEnum<T>()).
CREATE TYPE inventory.reservation_status AS ENUM ('soft', 'firm', 'consumed', 'released', 'expired');
CREATE TYPE inventory.transfer_status    AS ENUM ('proposed', 'approved', 'dispatched', 'received', 'cancelled');
COMMENT ON TYPE inventory.reservation_status IS 'soft = 7-day service-kit hold (UC02); firm = hold for an approved transfer; consumed/released/expired = closed.';
COMMENT ON TYPE inventory.transfer_status IS 'Transfer order life cycle: proposed -> approved -> dispatched -> received; cancelled from proposed/approved.';

-- ---------------------------------------------------------------------------
-- SKU at location: slowly changing master data (policy), separated from the
-- hot, frequently updated balance row.
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.warehouse_part (
    warehouse_id      smallint       NOT NULL,
    part_id           bigint         NOT NULL,
    bin_location      varchar(20),
    safety_stock_qty  numeric(12,3)  NOT NULL DEFAULT 0,
    max_stock_qty     numeric(12,3),
    is_stocked        boolean        NOT NULL DEFAULT true,
    updated_at        timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_warehouse_part PRIMARY KEY (warehouse_id, part_id),
    CONSTRAINT fk_warehouse_part_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouse (id) ON DELETE RESTRICT,
    CONSTRAINT fk_warehouse_part_part      FOREIGN KEY (part_id)      REFERENCES catalog.part (id) ON DELETE RESTRICT,
    CONSTRAINT ck_warehouse_part_safety CHECK (safety_stock_qty >= 0),
    CONSTRAINT ck_warehouse_part_max    CHECK (max_stock_qty IS NULL OR max_stock_qty >= safety_stock_qty),
    CONSTRAINT ck_warehouse_part_bin    CHECK (bin_location IS NULL OR bin_location ~ '^[A-Z0-9-]{2,20}$')
);
CREATE INDEX ix_warehouse_part_part ON inventory.warehouse_part (part_id);
CREATE TRIGGER trg_warehouse_part_updated_at BEFORE UPDATE ON inventory.warehouse_part
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  inventory.warehouse_part IS 'Stocking policy of a part in a warehouse: shelf location, safety stock, maximum.';
COMMENT ON COLUMN inventory.warehouse_part.safety_stock_qty IS 'Local safety buffer; a donor hub may only give away stock above it (US10).';

-- ---------------------------------------------------------------------------
-- Stock balance: derived state of the ledger, maintained ONLY by triggers.
-- Application roles have no UPDATE privilege on it (see V015).
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.stock_balance (
    warehouse_id      smallint       NOT NULL,
    part_id           bigint         NOT NULL,
    on_hand_qty       numeric(12,3)  NOT NULL DEFAULT 0,
    reserved_qty      numeric(12,3)  NOT NULL DEFAULT 0,
    available_qty     numeric(12,3)  GENERATED ALWAYS AS (on_hand_qty - reserved_qty) STORED,
    last_movement_at  timestamptz,
    updated_at        timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_stock_balance PRIMARY KEY (warehouse_id, part_id),
    CONSTRAINT fk_stock_balance_warehouse_part FOREIGN KEY (warehouse_id, part_id)
        REFERENCES inventory.warehouse_part (warehouse_id, part_id) ON DELETE RESTRICT,
    -- NFR03: no negative stock, no over-reservation — guaranteed by the DBMS.
    CONSTRAINT ck_stock_balance_on_hand_non_negative  CHECK (on_hand_qty >= 0),
    CONSTRAINT ck_stock_balance_reserved_non_negative CHECK (reserved_qty >= 0),
    CONSTRAINT ck_stock_balance_reserved_le_on_hand   CHECK (reserved_qty <= on_hand_qty)
);
CREATE INDEX ix_stock_balance_part ON inventory.stock_balance (part_id);
COMMENT ON TABLE  inventory.stock_balance IS 'Current stock per warehouse and part. Controlled redundancy: = SUM of the ledger, kept in sync by triggers for O(1) reads (NFR01).';
COMMENT ON COLUMN inventory.stock_balance.available_qty IS 'Generated column: on_hand - reserved (never stored inconsistently).';

-- ---------------------------------------------------------------------------
-- Stock movement ledger — append-only, RANGE-partitioned by month.
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.stock_movement (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    occurred_at             timestamptz    NOT NULL,
    warehouse_id            smallint       NOT NULL,
    part_id                 bigint         NOT NULL,
    movement_type_code      varchar(20)    NOT NULL,
    quantity                numeric(12,3)  NOT NULL,
    unit_cost               numeric(12,2),
    service_order_line_id   bigint,
    transfer_order_line_id  bigint,
    purchase_order_line_id  bigint,
    import_batch_id         bigint,
    external_doc_ref        varchar(40),
    note                    varchar(300),
    created_by              uuid,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_stock_movement PRIMARY KEY (id, occurred_at),
    CONSTRAINT fk_stock_movement_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT fk_stock_movement_part      FOREIGN KEY (part_id)      REFERENCES catalog.part (id),
    CONSTRAINT fk_stock_movement_type      FOREIGN KEY (movement_type_code) REFERENCES ref.movement_type (code),
    CONSTRAINT fk_stock_movement_created_by FOREIGN KEY (created_by) REFERENCES iam.app_user (id),
    CONSTRAINT ck_stock_movement_quantity  CHECK (quantity > 0),
    CONSTRAINT ck_stock_movement_unit_cost CHECK (unit_cost IS NULL OR unit_cost >= 0),
    -- Each movement type must reference its source document (lineage).
    CONSTRAINT ck_stock_movement_source_document CHECK (
        CASE movement_type_code
            WHEN 'RECEIPT_PO'        THEN purchase_order_line_id IS NOT NULL
            WHEN 'TRANSFER_OUT'      THEN transfer_order_line_id IS NOT NULL
            WHEN 'TRANSFER_IN'       THEN transfer_order_line_id IS NOT NULL
            WHEN 'ISSUE_SERVICE'     THEN service_order_line_id  IS NOT NULL
            WHEN 'ISSUE_SALE'        THEN external_doc_ref       IS NOT NULL
            WHEN 'HISTORICAL_DEMAND' THEN import_batch_id        IS NOT NULL
            WHEN 'ADJUSTMENT_IN'     THEN note                   IS NOT NULL
            WHEN 'ADJUSTMENT_OUT'    THEN note                   IS NOT NULL
            ELSE true
        END),
    CONSTRAINT ck_stock_movement_single_document CHECK (
        num_nonnulls(service_order_line_id, transfer_order_line_id, purchase_order_line_id, import_batch_id) <= 1)
) PARTITION BY RANGE (occurred_at);

-- Indexes on the partitioned parent are created on every partition.
-- (1) demand aggregation per SKU/location over time (mart refresh, US04 history)
CREATE INDEX ix_stock_movement_part_wh_time ON inventory.stock_movement (part_id, warehouse_id, occurred_at);
-- (2) BRIN: tiny index for time-range scans on an append-only, time-ordered table
CREATE INDEX ix_stock_movement_occurred_brin ON inventory.stock_movement USING brin (occurred_at);
-- (3) lineage look-ups, partial because most rows have NULL here
CREATE INDEX ix_stock_movement_transfer_line ON inventory.stock_movement (transfer_order_line_id) WHERE transfer_order_line_id IS NOT NULL;
CREATE INDEX ix_stock_movement_service_line  ON inventory.stock_movement (service_order_line_id)  WHERE service_order_line_id  IS NOT NULL;
CREATE INDEX ix_stock_movement_po_line       ON inventory.stock_movement (purchase_order_line_id) WHERE purchase_order_line_id IS NOT NULL;
CREATE INDEX ix_stock_movement_import_batch  ON inventory.stock_movement (import_batch_id)        WHERE import_batch_id        IS NOT NULL;

COMMENT ON TABLE  inventory.stock_movement IS 'Append-only stock ledger (single source of truth for stock and demand history). Partitioned by month; corrections only via compensating movements.';
COMMENT ON COLUMN inventory.stock_movement.quantity IS 'Always positive; direction comes from ref.movement_type.balance_sign.';
COMMENT ON COLUMN inventory.stock_movement.unit_cost IS 'Valuation cost per unit at the time of the movement (EUR).';

-- Partitions: 2024-01 .. 2028-12 + DEFAULT (safety net). A monthly job keeps
-- creating partitions 12 months ahead (util.ensure_monthly_partitions).
SELECT util.ensure_monthly_partitions('inventory.stock_movement', DATE '2024-01-01', 60);
CREATE TABLE inventory.stock_movement_default PARTITION OF inventory.stock_movement DEFAULT;

-- ---------------------------------------------------------------------------
-- Exceptional (one-off) demand flag — 1:1 extension of a demand movement (US08)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.demand_exception (
    movement_id           bigint        NOT NULL,
    movement_occurred_at  timestamptz   NOT NULL,
    reason                varchar(300)  NOT NULL,
    detection_method      varchar(20)   NOT NULL DEFAULT 'manual',
    flagged_by            uuid,
    flagged_at            timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_demand_exception PRIMARY KEY (movement_id, movement_occurred_at),
    CONSTRAINT fk_demand_exception_movement FOREIGN KEY (movement_id, movement_occurred_at)
        REFERENCES inventory.stock_movement (id, occurred_at) ON DELETE CASCADE,
    CONSTRAINT fk_demand_exception_flagged_by FOREIGN KEY (flagged_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_demand_exception_reason CHECK (length(btrim(reason)) >= 5),
    CONSTRAINT ck_demand_exception_method CHECK (detection_method IN ('manual', 'auto_3sigma'))
);
CREATE INDEX ix_demand_exception_flagged_by ON inventory.demand_exception (flagged_by);
COMMENT ON TABLE inventory.demand_exception IS '1:1 annotation of a demand movement as exceptional (US08). Kept separate because the ledger is immutable; excluded from ML training.';

-- ---------------------------------------------------------------------------
-- Reservations (soft = service kit for 7 days, firm = approved transfer)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.stock_reservation (
    id                      bigint                        GENERATED BY DEFAULT AS IDENTITY,
    warehouse_id            smallint                      NOT NULL,
    part_id                 bigint                        NOT NULL,
    quantity                numeric(12,3)                 NOT NULL,
    status                  inventory.reservation_status  NOT NULL DEFAULT 'soft',
    expires_at              timestamptz,
    service_order_line_id   bigint,
    transfer_order_line_id  bigint,
    created_by              uuid,
    created_at              timestamptz                   NOT NULL DEFAULT now(),
    closed_at               timestamptz,
    CONSTRAINT pk_stock_reservation PRIMARY KEY (id),
    CONSTRAINT fk_stock_reservation_balance FOREIGN KEY (warehouse_id, part_id)
        REFERENCES inventory.stock_balance (warehouse_id, part_id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_reservation_created_by FOREIGN KEY (created_by) REFERENCES iam.app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_stock_reservation_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_reservation_one_source CHECK (num_nonnulls(service_order_line_id, transfer_order_line_id) = 1),
    CONSTRAINT ck_stock_reservation_soft_expires CHECK (status <> 'soft' OR expires_at IS NOT NULL),
    CONSTRAINT ck_stock_reservation_closed CHECK ((status IN ('soft', 'firm')) = (closed_at IS NULL))
);
-- Expiry job scans only active soft reservations (partial index).
CREATE INDEX ix_stock_reservation_soft_expiry ON inventory.stock_reservation (expires_at) WHERE status = 'soft';
CREATE INDEX ix_stock_reservation_active ON inventory.stock_reservation (warehouse_id, part_id) WHERE status IN ('soft', 'firm');
CREATE INDEX ix_stock_reservation_service_line  ON inventory.stock_reservation (service_order_line_id)  WHERE service_order_line_id  IS NOT NULL;
CREATE INDEX ix_stock_reservation_transfer_line ON inventory.stock_reservation (transfer_order_line_id) WHERE transfer_order_line_id IS NOT NULL;
CREATE INDEX ix_stock_reservation_created_by ON inventory.stock_reservation (created_by);
COMMENT ON TABLE inventory.stock_reservation IS 'Stock holds. Active (soft/firm) quantities are summed into stock_balance.reserved_qty by trigger.';

-- ---------------------------------------------------------------------------
-- Inter-warehouse transfers (US10, US11)
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.transfer_order (
    id                 bigint                     GENERATED BY DEFAULT AS IDENTITY,
    number             varchar(20)                NOT NULL,
    from_warehouse_id  smallint                   NOT NULL,
    to_warehouse_id    smallint                   NOT NULL,
    status             inventory.transfer_status  NOT NULL DEFAULT 'proposed',
    is_urgent          boolean                    NOT NULL DEFAULT false,
    requested_by       uuid,
    approved_by        uuid,
    approved_at        timestamptz,
    dispatched_by      uuid,
    dispatched_at      timestamptz,
    received_by        uuid,
    received_at        timestamptz,
    cancel_reason      varchar(300),
    created_at         timestamptz                NOT NULL DEFAULT now(),
    updated_at         timestamptz                NOT NULL DEFAULT now(),
    CONSTRAINT pk_transfer_order PRIMARY KEY (id),
    CONSTRAINT uq_transfer_order_number UNIQUE (number),
    -- A transfer is only possible along a known route of the transport matrix.
    CONSTRAINT fk_transfer_order_route FOREIGN KEY (from_warehouse_id, to_warehouse_id)
        REFERENCES inventory.warehouse_route (from_warehouse_id, to_warehouse_id),
    CONSTRAINT fk_transfer_order_requested_by  FOREIGN KEY (requested_by)  REFERENCES iam.app_user (id),
    CONSTRAINT fk_transfer_order_approved_by   FOREIGN KEY (approved_by)   REFERENCES iam.app_user (id),
    CONSTRAINT fk_transfer_order_dispatched_by FOREIGN KEY (dispatched_by) REFERENCES iam.app_user (id),
    CONSTRAINT fk_transfer_order_received_by   FOREIGN KEY (received_by)   REFERENCES iam.app_user (id),
    CONSTRAINT ck_transfer_order_number CHECK (number ~ '^TR-\d{4}-\d{6}$'),
    CONSTRAINT ck_transfer_order_distinct CHECK (from_warehouse_id <> to_warehouse_id),
    CONSTRAINT ck_transfer_order_approved   CHECK (status IN ('proposed', 'cancelled') OR approved_at IS NOT NULL),
    CONSTRAINT ck_transfer_order_dispatched CHECK (status NOT IN ('dispatched', 'received') OR dispatched_at IS NOT NULL),
    CONSTRAINT ck_transfer_order_received   CHECK ((status = 'received') = (received_at IS NOT NULL)),
    CONSTRAINT ck_transfer_order_timeline   CHECK (dispatched_at IS NULL OR dispatched_at >= approved_at),
    CONSTRAINT ck_transfer_order_timeline2  CHECK (received_at IS NULL OR received_at >= dispatched_at),
    CONSTRAINT ck_transfer_order_cancel     CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL))
);
CREATE INDEX ix_transfer_order_to_wh ON inventory.transfer_order (to_warehouse_id);
CREATE INDEX ix_transfer_order_open  ON inventory.transfer_order (status, created_at) WHERE status IN ('proposed', 'approved', 'dispatched');
CREATE INDEX ix_transfer_order_requested_by  ON inventory.transfer_order (requested_by);
CREATE INDEX ix_transfer_order_approved_by   ON inventory.transfer_order (approved_by);
CREATE INDEX ix_transfer_order_dispatched_by ON inventory.transfer_order (dispatched_by);
CREATE INDEX ix_transfer_order_received_by   ON inventory.transfer_order (received_by);
CREATE TRIGGER trg_transfer_order_updated_at BEFORE UPDATE ON inventory.transfer_order
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE inventory.transfer_order IS 'Inter-warehouse transfer order (TR-YYYY-NNNNNN). Status changes only through inventory.approve/dispatch/receive/cancel_transfer().';

CREATE TABLE inventory.transfer_order_line (
    id                 bigint         GENERATED BY DEFAULT AS IDENTITY,
    transfer_order_id  bigint         NOT NULL,
    part_id            bigint         NOT NULL,
    quantity           numeric(12,3)  NOT NULL,
    proposed_qty       numeric(12,3),
    override_reason    varchar(300),
    CONSTRAINT pk_transfer_order_line PRIMARY KEY (id),
    CONSTRAINT uq_transfer_order_line_part UNIQUE (transfer_order_id, part_id),
    CONSTRAINT fk_transfer_order_line_order FOREIGN KEY (transfer_order_id) REFERENCES inventory.transfer_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_transfer_order_line_part  FOREIGN KEY (part_id) REFERENCES catalog.part (id),
    CONSTRAINT ck_transfer_order_line_qty CHECK (quantity > 0),
    CONSTRAINT ck_transfer_order_line_proposed CHECK (proposed_qty IS NULL OR proposed_qty > 0),
    -- UC01 A2: a manual change of the proposed quantity requires a justification.
    CONSTRAINT ck_transfer_order_line_override CHECK (proposed_qty IS NULL OR quantity = proposed_qty OR override_reason IS NOT NULL)
);
CREATE INDEX ix_transfer_order_line_part ON inventory.transfer_order_line (part_id);
COMMENT ON TABLE inventory.transfer_order_line IS 'Parts and quantities of a transfer; proposed_qty keeps the system proposal for KPI-04 (acceptance rate).';

-- Late-bound foreign keys to transfer lines (table now exists).
ALTER TABLE inventory.stock_reservation
    ADD CONSTRAINT fk_stock_reservation_transfer_line FOREIGN KEY (transfer_order_line_id)
        REFERENCES inventory.transfer_order_line (id) ON DELETE CASCADE;
ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT fk_stock_movement_transfer_line FOREIGN KEY (transfer_order_line_id)
        REFERENCES inventory.transfer_order_line (id);
