-- =============================================================================
-- V003 — Warehouses (7 regional hubs), transport matrix, parts catalogue,
--        suppliers, supplier conditions (US12) and supplier price history.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Warehouses
-- ---------------------------------------------------------------------------
CREATE TABLE inventory.warehouse (
    id              smallint      GENERATED BY DEFAULT AS IDENTITY,
    code            varchar(10)   NOT NULL,
    name            varchar(120)  NOT NULL,
    city            varchar(80)   NOT NULL,
    address         varchar(200),
    is_central_hub  boolean       NOT NULL DEFAULT false,
    latitude        numeric(8,5),
    longitude       numeric(8,5),
    is_active       boolean       NOT NULL DEFAULT true,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_warehouse PRIMARY KEY (id),
    CONSTRAINT uq_warehouse_code UNIQUE (code),
    CONSTRAINT ck_warehouse_code CHECK (code ~ '^[A-Z]{3,10}$'),
    CONSTRAINT ck_warehouse_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_warehouse_lon CHECK (longitude BETWEEN -180 AND 180)
);
-- At most one central hub in the network.
CREATE UNIQUE INDEX uq_warehouse_single_central_hub ON inventory.warehouse (is_central_hub) WHERE is_central_hub;
COMMENT ON TABLE inventory.warehouse IS 'Regional branch warehouses (Vilnius central hub, Kaunas, Klaipėda, Šiauliai, Panevėžys, Marijampolė, Utena).';

CREATE TABLE inventory.warehouse_route (
    from_warehouse_id   smallint       NOT NULL,
    to_warehouse_id     smallint       NOT NULL,
    distance_km         numeric(6,1)   NOT NULL,
    transit_hours       numeric(5,1)   NOT NULL,
    transport_cost_eur  numeric(10,2)  NOT NULL,
    CONSTRAINT pk_warehouse_route PRIMARY KEY (from_warehouse_id, to_warehouse_id),
    CONSTRAINT fk_warehouse_route_from FOREIGN KEY (from_warehouse_id) REFERENCES inventory.warehouse (id) ON DELETE CASCADE,
    CONSTRAINT fk_warehouse_route_to   FOREIGN KEY (to_warehouse_id)   REFERENCES inventory.warehouse (id) ON DELETE CASCADE,
    CONSTRAINT ck_warehouse_route_distinct CHECK (from_warehouse_id <> to_warehouse_id),
    CONSTRAINT ck_warehouse_route_distance CHECK (distance_km > 0),
    CONSTRAINT ck_warehouse_route_transit  CHECK (transit_hours > 0 AND transit_hours <= 240),
    CONSTRAINT ck_warehouse_route_cost     CHECK (transport_cost_eur >= 0)
);
CREATE INDEX ix_warehouse_route_to ON inventory.warehouse_route (to_warehouse_id);
COMMENT ON TABLE inventory.warehouse_route IS 'Fixed inter-depot transport matrix (M:N warehouse-warehouse): distance, transit time, cost. Used by the rebalancing engine (US10).';

-- ---------------------------------------------------------------------------
-- Suppliers
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.supplier (
    id                      integer       GENERATED BY DEFAULT AS IDENTITY,
    code                    varchar(20)   NOT NULL,
    name                    varchar(200)  NOT NULL,
    country_code            char(2)       NOT NULL,
    order_email             citext,
    default_lead_time_days  smallint      NOT NULL,
    currency_code           char(3)       NOT NULL DEFAULT 'EUR',
    is_active               boolean       NOT NULL DEFAULT true,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_supplier PRIMARY KEY (id),
    CONSTRAINT uq_supplier_code UNIQUE (code),
    CONSTRAINT uq_supplier_name UNIQUE (name),
    CONSTRAINT ck_supplier_country CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_supplier_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_supplier_email CHECK (order_email IS NULL OR order_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_supplier_lead_time CHECK (default_lead_time_days BETWEEN 1 AND 365)
);
CREATE TRIGGER trg_supplier_updated_at BEFORE UPDATE ON catalog.supplier
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  catalog.supplier IS 'OEM suppliers / distributors. Business contact data only (no personal data).';
COMMENT ON COLUMN catalog.supplier.order_email IS 'Shared order mailbox of the company (e.g. orders@...), not a personal address.';

-- ---------------------------------------------------------------------------
-- Spare parts (SKU catalogue, US03)
-- ---------------------------------------------------------------------------
CREATE TABLE catalog.part (
    id                  bigint         GENERATED BY DEFAULT AS IDENTITY,
    brand_id            smallint       NOT NULL,
    oem_part_number     varchar(40)    NOT NULL,
    description         varchar(300)   NOT NULL,
    category_id         integer        NOT NULL,
    uom_id              smallint       NOT NULL,
    weight_kg           numeric(9,3),
    unit_cost           numeric(12,2)  NOT NULL,
    is_condition_based  boolean        NOT NULL DEFAULT false,
    is_active           boolean        NOT NULL DEFAULT true,
    created_at          timestamptz    NOT NULL DEFAULT now(),
    updated_at          timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_part PRIMARY KEY (id),
    CONSTRAINT uq_part_brand_oem UNIQUE (brand_id, oem_part_number),
    CONSTRAINT fk_part_brand    FOREIGN KEY (brand_id)    REFERENCES ref.brand (id),
    CONSTRAINT fk_part_category FOREIGN KEY (category_id) REFERENCES ref.part_category (id),
    CONSTRAINT fk_part_uom      FOREIGN KEY (uom_id)      REFERENCES ref.unit_of_measure (id),
    CONSTRAINT ck_part_oem_number CHECK (oem_part_number ~ '^[A-Z0-9][A-Z0-9.\-/]{2,39}$'),
    CONSTRAINT ck_part_description CHECK (length(btrim(description)) >= 3),
    CONSTRAINT ck_part_weight CHECK (weight_kg IS NULL OR weight_kg >= 0),
    CONSTRAINT ck_part_unit_cost CHECK (unit_cost >= 0)
);
CREATE INDEX ix_part_category ON catalog.part (category_id);
CREATE INDEX ix_part_uom      ON catalog.part (uom_id);
-- Search-as-you-type over 20,000 SKUs (NFR01 <= 2 s): trigram GIN supports ILIKE '%...%'.
CREATE INDEX ix_part_oem_number_trgm  ON catalog.part USING gin (oem_part_number gin_trgm_ops);
CREATE INDEX ix_part_description_trgm ON catalog.part USING gin (description gin_trgm_ops);
CREATE TRIGGER trg_part_updated_at BEFORE UPDATE ON catalog.part
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  catalog.part IS 'Spare part (SKU) catalogue; natural key = brand + OEM part number.';
COMMENT ON COLUMN catalog.part.oem_part_number IS 'Manufacturer part number, upper-case, normalised during import.';
COMMENT ON COLUMN catalog.part.unit_cost IS 'Standard (valuation) cost per unit, EUR. Money is numeric, never float.';
COMMENT ON COLUMN catalog.part.is_condition_based IS 'TRUE for parts replaced "as required" (air/cab filters, finding F6): demand only from the forecast stream.';

-- Analogue linking for new SKUs (US15): self-referencing M:N part <-> part.
CREATE TABLE catalog.part_analogue (
    part_id           bigint        NOT NULL,
    analogue_part_id  bigint        NOT NULL,
    scaling_factor    numeric(5,3)  NOT NULL DEFAULT 1.000,
    valid_from        date          NOT NULL DEFAULT current_date,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_part_analogue PRIMARY KEY (part_id, analogue_part_id),
    CONSTRAINT fk_part_analogue_part     FOREIGN KEY (part_id)          REFERENCES catalog.part (id) ON DELETE CASCADE,
    CONSTRAINT fk_part_analogue_analogue FOREIGN KEY (analogue_part_id) REFERENCES catalog.part (id) ON DELETE RESTRICT,
    CONSTRAINT ck_part_analogue_distinct CHECK (part_id <> analogue_part_id),
    CONSTRAINT ck_part_analogue_factor   CHECK (scaling_factor > 0 AND scaling_factor <= 10)
);
CREATE INDEX ix_part_analogue_analogue ON catalog.part_analogue (analogue_part_id);
COMMENT ON TABLE catalog.part_analogue IS 'New SKU -> historical analogue/predecessor SKU with a demand scaling factor (US15).';

-- Supplier conditions per part (US12): M:N supplier <-> part with attributes.
CREATE TABLE catalog.supplier_part (
    id                    bigint         GENERATED BY DEFAULT AS IDENTITY,
    supplier_id           integer        NOT NULL,
    part_id               bigint         NOT NULL,
    supplier_part_number  varchar(40),
    moq                   numeric(12,3)  NOT NULL DEFAULT 1,
    pack_size             numeric(12,3)  NOT NULL DEFAULT 1,
    lead_time_days        smallint       NOT NULL,
    is_preferred          boolean        NOT NULL DEFAULT false,
    created_at            timestamptz    NOT NULL DEFAULT now(),
    updated_at            timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_supplier_part PRIMARY KEY (id),
    CONSTRAINT uq_supplier_part UNIQUE (supplier_id, part_id),
    CONSTRAINT fk_supplier_part_supplier FOREIGN KEY (supplier_id) REFERENCES catalog.supplier (id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_part_part     FOREIGN KEY (part_id)     REFERENCES catalog.part (id) ON DELETE CASCADE,
    CONSTRAINT ck_supplier_part_moq       CHECK (moq > 0),
    CONSTRAINT ck_supplier_part_pack      CHECK (pack_size > 0),
    CONSTRAINT ck_supplier_part_moq_pack  CHECK (mod(moq, pack_size) = 0),
    CONSTRAINT ck_supplier_part_lead_time CHECK (lead_time_days BETWEEN 1 AND 365)
);
CREATE INDEX ix_supplier_part_part ON catalog.supplier_part (part_id);
-- Exactly zero or one preferred supplier per part.
CREATE UNIQUE INDEX uq_supplier_part_preferred ON catalog.supplier_part (part_id) WHERE is_preferred;
CREATE TRIGGER trg_supplier_part_updated_at BEFORE UPDATE ON catalog.supplier_part
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  catalog.supplier_part IS 'Commercial conditions of a supplier for a part: MOQ, pack size, lead time (US12).';
COMMENT ON COLUMN catalog.supplier_part.moq IS 'Minimum order quantity; must be a multiple of pack_size.';

-- Price history: validity ranges must not overlap (EXCLUDE constraint, btree_gist).
CREATE TABLE catalog.supplier_price (
    id                bigint         GENERATED BY DEFAULT AS IDENTITY,
    supplier_part_id  bigint         NOT NULL,
    valid_during      daterange      NOT NULL,
    unit_price        numeric(12,2)  NOT NULL,
    CONSTRAINT pk_supplier_price PRIMARY KEY (id),
    CONSTRAINT fk_supplier_price_supplier_part FOREIGN KEY (supplier_part_id) REFERENCES catalog.supplier_part (id) ON DELETE CASCADE,
    CONSTRAINT ck_supplier_price_amount CHECK (unit_price > 0),
    CONSTRAINT ck_supplier_price_range CHECK (NOT isempty(valid_during) AND lower(valid_during) IS NOT NULL),
    CONSTRAINT ex_supplier_price_no_overlap EXCLUDE USING gist (supplier_part_id WITH =, valid_during WITH &&)
);
COMMENT ON TABLE  catalog.supplier_price IS 'Supplier purchase price history; non-overlapping validity periods per supplier-part (EXCLUDE USING gist).';
COMMENT ON COLUMN catalog.supplier_price.valid_during IS 'Validity period [from, to); open upper bound = valid until further notice.';
