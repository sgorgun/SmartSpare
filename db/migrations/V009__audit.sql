-- =============================================================================
-- V009 — Immutable audit trail (US18), monthly partitions, 180-day retention
-- =============================================================================

CREATE TABLE audit.audit_log (
    id               bigint        GENERATED BY DEFAULT AS IDENTITY,
    occurred_at      timestamptz   NOT NULL DEFAULT clock_timestamp(),
    user_id          uuid,
    db_role          name          NOT NULL DEFAULT session_user,
    action           varchar(10)   NOT NULL,
    table_name       varchar(80)   NOT NULL,
    record_id        varchar(80)   NOT NULL,
    old_values       jsonb,
    new_values       jsonb,
    changed_columns  text[],
    reason           varchar(300),
    transaction_id   bigint        NOT NULL DEFAULT txid_current(),
    CONSTRAINT pk_audit_log PRIMARY KEY (id, occurred_at),
    CONSTRAINT fk_audit_log_user FOREIGN KEY (user_id) REFERENCES iam.app_user (id),
    CONSTRAINT ck_audit_log_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    -- jsonb is justified here: one generic audit table for many source tables with different
    -- column sets; values are only displayed, never joined. Must be JSON objects.
    CONSTRAINT ck_audit_log_old CHECK (old_values IS NULL OR jsonb_typeof(old_values) = 'object'),
    CONSTRAINT ck_audit_log_new CHECK (new_values IS NULL OR jsonb_typeof(new_values) = 'object'),
    CONSTRAINT ck_audit_log_shape CHECK (
        (action = 'INSERT' AND old_values IS NULL AND new_values IS NOT NULL) OR
        (action = 'UPDATE' AND old_values IS NOT NULL AND new_values IS NOT NULL) OR
        (action = 'DELETE' AND old_values IS NOT NULL AND new_values IS NULL))
) PARTITION BY RANGE (occurred_at);

CREATE INDEX ix_audit_log_record ON audit.audit_log (table_name, record_id, occurred_at DESC);
CREATE INDEX ix_audit_log_user   ON audit.audit_log (user_id, occurred_at DESC) WHERE user_id IS NOT NULL;
CREATE INDEX ix_audit_log_occurred_brin ON audit.audit_log USING brin (occurred_at);

SELECT util.ensure_monthly_partitions('audit.audit_log', DATE '2025-01-01', 48);
CREATE TABLE audit.audit_log_default PARTITION OF audit.audit_log DEFAULT;

-- Append-only: UPDATE and DELETE are rejected for everybody (incl. the owner);
-- retention works by dropping whole partitions (audit.purge_expired).
CREATE TRIGGER trg_audit_log_immutable BEFORE UPDATE OR DELETE ON audit.audit_log
    FOR EACH ROW EXECUTE FUNCTION util.trg_forbid_modification();

COMMENT ON TABLE  audit.audit_log IS 'Immutable audit trail of state-changing operations: timestamp, user, action, previous and new values, reason (US18).';
COMMENT ON COLUMN audit.audit_log.user_id IS 'Application user (GUC app.user_id); NULL for background jobs.';
COMMENT ON COLUMN audit.audit_log.reason IS 'Business justification (GUC app.reason), e.g. reason for a manual override.';
COMMENT ON COLUMN audit.audit_log.old_values IS 'Previous values of the changed columns only (personal data columns are excluded).';

-- ---------------------------------------------------------------------------
-- Generic row-audit trigger. TG_ARGV = columns that must NOT be copied into
-- the audit trail (personal data, password hashes, technical timestamps).
-- SECURITY DEFINER: application roles cannot write to audit.audit_log directly.
-- ---------------------------------------------------------------------------
CREATE FUNCTION audit.trg_row_audit() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    v_old      jsonb;
    v_new      jsonb;
    v_excluded text[] := ARRAY['updated_at'] || coalesce(TG_ARGV::text[], '{}');
    v_changed  text[];
    v_id       text;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN v_old := to_jsonb(OLD) - v_excluded; END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN v_new := to_jsonb(NEW) - v_excluded; END IF;

    IF TG_OP = 'UPDATE' THEN
        SELECT array_agg(n.key ORDER BY n.key) INTO v_changed
        FROM jsonb_each(v_new) n
        WHERE n.value IS DISTINCT FROM v_old -> n.key;
        IF v_changed IS NULL THEN RETURN NULL; END IF;     -- nothing relevant changed
        -- keep only the changed columns
        SELECT jsonb_object_agg(k, v_old -> k), jsonb_object_agg(k, v_new -> k)
          INTO v_old, v_new
        FROM unnest(v_changed) AS k;
    END IF;

    v_id := coalesce(v_new, v_old) ->> 'id';
    IF v_id IS NULL THEN  -- composite keys: concatenate *_id columns
        SELECT string_agg(value, '|' ORDER BY key) INTO v_id
        FROM jsonb_each_text(coalesce(to_jsonb(NEW), to_jsonb(OLD)))
        WHERE key LIKE '%\_id' ESCAPE '\';
    END IF;

    INSERT INTO audit.audit_log (user_id, action, table_name, record_id, old_values, new_values, changed_columns, reason)
    VALUES (nullif(current_setting('app.user_id', true), '')::uuid,
            TG_OP, TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME, coalesce(v_id, '?'),
            v_old, v_new, v_changed,
            nullif(current_setting('app.reason', true), ''));
    RETURN NULL;
END $$;
COMMENT ON FUNCTION audit.trg_row_audit() IS 'AFTER ROW trigger writing changed columns into audit.audit_log; arguments = excluded columns (PII, secrets).';

-- Retention (GDPR / BA 2.8: audit logs kept 180 days): drop whole expired partitions.
CREATE PROCEDURE audit.purge_expired(p_retention interval DEFAULT interval '180 days')
LANGUAGE plpgsql AS $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT c.oid::regclass AS part,
               (regexp_match(pg_get_expr(c.relpartbound, c.oid), 'TO \(''([^'']+)''\)'))[1]::timestamptz AS upper_bound
        FROM pg_inherits i
        JOIN pg_class c ON c.oid = i.inhrelid
        WHERE i.inhparent = 'audit.audit_log'::regclass
          AND pg_get_expr(c.relpartbound, c.oid) <> 'DEFAULT'
    LOOP
        IF r.upper_bound <= now() - p_retention THEN
            EXECUTE format('ALTER TABLE audit.audit_log DETACH PARTITION %s', r.part);
            EXECUTE format('DROP TABLE %s', r.part);
            RAISE NOTICE 'Dropped expired audit partition %', r.part;
        END IF;
    END LOOP;
END $$;
COMMENT ON PROCEDURE audit.purge_expired(interval) IS 'Drops audit partitions older than the retention period (default 180 days). Run monthly by Quartz.NET.';
