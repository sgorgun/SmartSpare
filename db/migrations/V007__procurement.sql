-- =============================================================================
-- V007 — Procurement module: purchase orders (US13, US14, US16)
-- =============================================================================

CREATE TYPE procurement.po_status AS ENUM
    ('draft', 'pending_approval', 'approved', 'exported', 'partially_received', 'received', 'cancelled');
COMMENT ON TYPE procurement.po_status IS 'PO life cycle; transitions are validated by trigger procurement.trg_po_status_transition.';

CREATE TABLE procurement.purchase_order (
    id                     bigint                 GENERATED BY DEFAULT AS IDENTITY,
    number                 varchar(20)            NOT NULL,
    supplier_id            integer                NOT NULL,
    warehouse_id           smallint               NOT NULL,
    status                 procurement.po_status  NOT NULL DEFAULT 'draft',
    is_urgent              boolean                NOT NULL DEFAULT false,
    urgent_reason          varchar(300),
    currency_code          char(3)                NOT NULL DEFAULT 'EUR',
    total_amount           numeric(14,2)          NOT NULL DEFAULT 0,
    expected_arrival_date  date,
    created_by             uuid                   NOT NULL,
    created_at             timestamptz            NOT NULL DEFAULT now(),
    submitted_at           timestamptz,
    approved_by            uuid,
    approved_at            timestamptz,
    exported_at            timestamptz,
    cancel_reason          varchar(300),
    updated_at             timestamptz            NOT NULL DEFAULT now(),
    CONSTRAINT pk_purchase_order PRIMARY KEY (id),
    CONSTRAINT uq_purchase_order_number UNIQUE (number),
    CONSTRAINT fk_purchase_order_supplier   FOREIGN KEY (supplier_id)  REFERENCES catalog.supplier (id),
    CONSTRAINT fk_purchase_order_warehouse  FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouse (id),
    CONSTRAINT fk_purchase_order_created_by FOREIGN KEY (created_by)   REFERENCES iam.app_user (id),
    CONSTRAINT fk_purchase_order_approved_by FOREIGN KEY (approved_by) REFERENCES iam.app_user (id),
    CONSTRAINT ck_purchase_order_number   CHECK (number ~ '^PO-\d{4}-\d{6}$'),
    CONSTRAINT ck_purchase_order_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_purchase_order_total    CHECK (total_amount >= 0),
    CONSTRAINT ck_purchase_order_urgent   CHECK (NOT is_urgent OR urgent_reason IS NOT NULL),
    CONSTRAINT ck_purchase_order_approved CHECK (
        status IN ('draft', 'pending_approval', 'cancelled') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)),
    -- US14 four-eyes principle: orders above EUR 5,000 cannot be approved by their author.
    CONSTRAINT ck_purchase_order_four_eyes CHECK (approved_by IS NULL OR total_amount <= 5000 OR approved_by <> created_by),
    CONSTRAINT ck_purchase_order_cancel CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL)),
    CONSTRAINT ck_purchase_order_timeline CHECK (approved_at IS NULL OR approved_at >= created_at)
);
CREATE INDEX ix_purchase_order_supplier_created ON procurement.purchase_order (supplier_id, created_at DESC);
CREATE INDEX ix_purchase_order_warehouse ON procurement.purchase_order (warehouse_id);
CREATE INDEX ix_purchase_order_open ON procurement.purchase_order (status, expected_arrival_date)
    WHERE status IN ('draft', 'pending_approval', 'approved', 'exported', 'partially_received');
CREATE INDEX ix_purchase_order_created_by  ON procurement.purchase_order (created_by);
CREATE INDEX ix_purchase_order_approved_by ON procurement.purchase_order (approved_by);
CREATE TRIGGER trg_purchase_order_updated_at BEFORE UPDATE ON procurement.purchase_order
    FOR EACH ROW EXECUTE FUNCTION util.trg_set_updated_at();
COMMENT ON TABLE  procurement.purchase_order IS 'Supplier purchase order (PO-YYYY-NNNNNN). Drafts are generated from recommendations and approved by management (US14).';
COMMENT ON COLUMN procurement.purchase_order.total_amount IS 'Controlled redundancy: SUM(line_amount), maintained by trigger; needed by the four-eyes CHECK.';
COMMENT ON COLUMN procurement.purchase_order.is_urgent IS 'US16 emergency direct purchase ("Urgent Harvest Dispatch"), bypasses weekly batching.';

CREATE TABLE procurement.purchase_order_line (
    id                 bigint         GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id  bigint         NOT NULL,
    part_id            bigint         NOT NULL,
    quantity           numeric(12,3)  NOT NULL,
    unit_price         numeric(12,2)  NOT NULL,
    line_amount        numeric(14,2)  GENERATED ALWAYS AS (round(quantity * unit_price, 2)) STORED,
    received_qty       numeric(12,3)  NOT NULL DEFAULT 0,
    proposed_qty       numeric(12,3),
    override_reason    varchar(300),
    CONSTRAINT pk_purchase_order_line PRIMARY KEY (id),
    CONSTRAINT uq_purchase_order_line_part UNIQUE (purchase_order_id, part_id),
    CONSTRAINT fk_purchase_order_line_order FOREIGN KEY (purchase_order_id) REFERENCES procurement.purchase_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_purchase_order_line_part  FOREIGN KEY (part_id) REFERENCES catalog.part (id),
    CONSTRAINT ck_purchase_order_line_qty CHECK (quantity > 0),
    CONSTRAINT ck_purchase_order_line_price CHECK (unit_price > 0),
    CONSTRAINT ck_purchase_order_line_received CHECK (received_qty >= 0 AND received_qty <= quantity),
    CONSTRAINT ck_purchase_order_line_override CHECK (proposed_qty IS NULL OR quantity = proposed_qty OR override_reason IS NOT NULL)
);
CREATE INDEX ix_purchase_order_line_part ON procurement.purchase_order_line (part_id);
COMMENT ON TABLE  procurement.purchase_order_line IS 'PO line. MOQ / pack-size rules of catalog.supplier_part are enforced by trigger.';
COMMENT ON COLUMN procurement.purchase_order_line.line_amount IS 'Generated column: round(quantity x unit_price, 2).';

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT fk_stock_movement_po_line FOREIGN KEY (purchase_order_line_id)
        REFERENCES procurement.purchase_order_line (id);
