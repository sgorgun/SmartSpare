-- Comments of the enum types, which EF creates (V005).
COMMENT ON TYPE inventory.reservation_status IS 'soft = 7-day service-kit hold (UC02); firm = hold for an approved transfer; consumed/released/expired = closed.';
COMMENT ON TYPE inventory.transfer_status IS 'Transfer order life cycle: proposed -> approved -> dispatched -> received; cancelled from proposed/approved.';

CREATE TABLE inventory.stock_movement (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    occurred_at             timestamptz    NOT NULL,
    warehouse_id            smallint       NOT NULL,
    part_id                 bigint         NOT NULL,
    movement_type_code      varchar(20)    NOT NULL,
    quantity                numeric(12,3)  NOT NULL,
    unit_cost               numeric(12,2),
    service_order_line_id   bigint,
    transfer_order_line_id  bigint,
    purchase_order_line_id  bigint,
    import_batch_id         bigint,
    external_doc_ref        varchar(40),
    note                    varchar(300),
    created_by              uuid,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_stock_movement PRIMARY KEY (id, occurred_at),
    CONSTRAINT fk_stock_movement_type      FOREIGN KEY (movement_type_code) REFERENCES ref.movement_type (code),
    CONSTRAINT ck_stock_movement_quantity  CHECK (quantity > 0),
    CONSTRAINT ck_stock_movement_unit_cost CHECK (unit_cost IS NULL OR unit_cost >= 0),
    -- Each movement type must reference its source document (lineage).
    CONSTRAINT ck_stock_movement_source_document CHECK (
        CASE movement_type_code
            WHEN 'RECEIPT_PO'        THEN purchase_order_line_id IS NOT NULL
            WHEN 'TRANSFER_OUT'      THEN transfer_order_line_id IS NOT NULL
            WHEN 'TRANSFER_IN'       THEN transfer_order_line_id IS NOT NULL
            WHEN 'ISSUE_SERVICE'     THEN service_order_line_id  IS NOT NULL
            WHEN 'ISSUE_SALE'        THEN external_doc_ref       IS NOT NULL
            WHEN 'HISTORICAL_DEMAND' THEN import_batch_id        IS NOT NULL
            WHEN 'ADJUSTMENT_IN'     THEN note                   IS NOT NULL
            WHEN 'ADJUSTMENT_OUT'    THEN note                   IS NOT NULL
            ELSE true
        END),
    CONSTRAINT ck_stock_movement_single_document CHECK (
        num_nonnulls(service_order_line_id, transfer_order_line_id, purchase_order_line_id, import_batch_id) <= 1)
) PARTITION BY RANGE (occurred_at);

CREATE INDEX ix_stock_movement_part_wh_time ON inventory.stock_movement (part_id, warehouse_id, occurred_at);

CREATE INDEX ix_stock_movement_occurred_brin ON inventory.stock_movement USING brin (occurred_at);

CREATE INDEX ix_stock_movement_transfer_line ON inventory.stock_movement (transfer_order_line_id) WHERE transfer_order_line_id IS NOT NULL;

CREATE INDEX ix_stock_movement_service_line  ON inventory.stock_movement (service_order_line_id)  WHERE service_order_line_id  IS NOT NULL;

CREATE INDEX ix_stock_movement_po_line       ON inventory.stock_movement (purchase_order_line_id) WHERE purchase_order_line_id IS NOT NULL;

CREATE INDEX ix_stock_movement_import_batch  ON inventory.stock_movement (import_batch_id)        WHERE import_batch_id        IS NOT NULL;

SELECT util.ensure_monthly_partitions('inventory.stock_movement', DATE '2024-01-01', 60);

CREATE TABLE inventory.stock_movement_default PARTITION OF inventory.stock_movement DEFAULT;

COMMENT ON TABLE inventory.stock_movement IS 'Append-only stock ledger (single source of truth for stock and demand history). Partitioned by month; corrections only via compensating movements.';
COMMENT ON COLUMN inventory.stock_movement.occurred_at IS 'Business time of the movement; partition key (monthly ranges).';
COMMENT ON COLUMN inventory.stock_movement.warehouse_id IS 'Reference to inventory.warehouse.';
COMMENT ON COLUMN inventory.stock_movement.part_id IS 'Reference to catalog.part.';
COMMENT ON COLUMN inventory.stock_movement.movement_type_code IS 'Type of movement; defines the sign (+/-/0) and whether it is demand.';
COMMENT ON COLUMN inventory.stock_movement.quantity IS 'Always positive; direction comes from ref.movement_type.balance_sign.';
COMMENT ON COLUMN inventory.stock_movement.unit_cost IS 'Valuation cost per unit at the time of the movement (EUR).';
COMMENT ON COLUMN inventory.stock_movement.service_order_line_id IS 'Reference to fleet.service_order_line.';
COMMENT ON COLUMN inventory.stock_movement.transfer_order_line_id IS 'Reference to inventory.transfer_order_line.';
COMMENT ON COLUMN inventory.stock_movement.purchase_order_line_id IS 'Reference to procurement.purchase_order_line.';
COMMENT ON COLUMN inventory.stock_movement.import_batch_id IS 'Reference to raw.import_batch.';
COMMENT ON COLUMN inventory.stock_movement.external_doc_ref IS 'Document number in an external system (POS receipt, ERP document).';
COMMENT ON COLUMN inventory.stock_movement.created_by IS 'User who created the record (iam.app_user).';
COMMENT ON COLUMN inventory.stock_movement.created_at IS 'Time the record was created.';
