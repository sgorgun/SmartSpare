using System.Globalization;
using System.Security.Claims;
using Microsoft.AspNetCore.Antiforgery;
using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.DependencyInjection;
using SmartSpare.ApiContracts;
using SmartSpare.ApiContracts.Authorization;
using SmartSpare.ApiContracts.Identity;
using SmartSpare.Infrastructure.Http;
using SmartSpare.Modules.Identity.Contracts;

namespace SmartSpare.Bff;

/// <summary>
/// Browser-session endpoints under <c>/bff</c> (STAGE_3_PLAN section 1.2, ADR 0014, ADR 0016). Unversioned, because they
/// are plumbing of the web client, not public API. Every unsafe request needs an antiforgery token, sign-in included.
/// </summary>
public static class BffEndpoints
{
    private static readonly LoginRequestValidator LoginValidator = new();

    /// <summary>Name of the OpenAPI document of these endpoints, <c>/openapi/bff.json</c> (ADR 0019, amendment 1).</summary>
    public const string DocumentName = "bff";

    private const string ExampleUser = "tomas.radzevicius";

    /// <summary>
    /// The <c>bff</c> document, generated by the host that serves the endpoints (the gateway or the single host), not by a
    /// service: only paths under <c>/bff/</c>.
    /// </summary>
    public static IServiceCollection AddBffDocument(this IServiceCollection services) =>
        services.AddApiDocument(
            DocumentName,
            "SmartSpare Session API (BFF)",
            "Sign-in, sign-out and the current user of the browser session (ADR 0014, ADR 0016). The session is an HttpOnly "
            + "cookie, __Host-SmartSpare; no token ever reaches the client. Every POST needs the antiforgery token from "
            + "GET /bff/antiforgery in the X-XSRF-TOKEN header, and a new token after sign-in, because it is bound to the user.",
            path => path is not null && path.TrimStart('/').StartsWith("bff/", StringComparison.OrdinalIgnoreCase));

    public static RouteGroupBuilder MapBff(this IEndpointRouteBuilder endpoints)
    {
        var group = endpoints.MapGroup("/bff")
            .WithTags("Session")
            .AddEndpointFilter<AntiforgeryValidationFilter>();

        group.MapPost("/login", LoginAsync)
            .AllowAnonymous()
            .RequireRateLimiting(BffDefaults.LoginRateLimitPolicy)
            .WithName("BffLogin")
            .WithSummary("Signs in with a user name and password.")
            .WithDescription(
                "Checks the credentials with the Identity module and, on success, sets the session cookie __Host-SmartSpare "
                + "(HttpOnly, Secure, SameSite=Strict, 8 h sliding; persistent only with rememberMe) and answers 204. Every "
                + "failure, including an invalid body, an unknown user, a wrong password, a locked or inactive account, is "
                + "the same 400 with code SS-AUTH-001, so the answer never reveals whether an account exists. A missing or "
                + "invalid X-XSRF-TOKEN header gives 400 SS-AUTH-002. Sign-in attempts are rate-limited per client: 429 "
                + "SS-AUTH-005 with Retry-After.")
            .Produces(StatusCodes.Status204NoContent)
            .ProducesProblem(StatusCodes.Status400BadRequest)
            .ProducesTooManyRequests()
            .WithRequestExample(new LoginRequest(ExampleUser, "your password", RememberMe: false))
            .WithResponseExample(StatusCodes.Status400BadRequest, OpenApiConventions.Problem(
                StatusCodes.Status400BadRequest, "Sign-in failed", ProblemCodes.InvalidCredentials, "The user name or password is incorrect."));

        group.MapPost("/logout", LogoutAsync)
            .RequireAuthorization()
            .WithName("BffLogout")
            .WithSummary("Signs out and removes the session cookie.")
            .WithDescription(
                "Ends the session of the cookie and answers 204. Needs the X-XSRF-TOKEN header (400 SS-AUTH-002 without "
                + "it) and a signed-in session (401 SS-AUTH-003 without one).")
            .Produces(StatusCodes.Status204NoContent)
            .ProducesProblem(StatusCodes.Status400BadRequest)
            .ProducesProblem(StatusCodes.Status401Unauthorized)
            .WithResponseExample(StatusCodes.Status400BadRequest, OpenApiConventions.Problem(
                StatusCodes.Status400BadRequest, "Antiforgery validation failed", ProblemCodes.AntiforgeryFailed,
                "The request is missing a valid antiforgery token. Reload the page and try again."))
            .WithResponseExample(StatusCodes.Status401Unauthorized, OpenApiConventions.Problem(
                StatusCodes.Status401Unauthorized, "Unauthorized", ProblemCodes.Unauthenticated));

        group.MapGet("/me", Me)
            .AllowAnonymous()
            .WithName("BffMe")
            .WithSummary("Returns the current user of the session.")
            .WithDescription(
                "Built from the claims of the cookie, without a database call. Anonymous callers get 200 with "
                + "isAuthenticated false and empty lists, so the client can check the session without an error.")
            .WithResponseExample(StatusCodes.Status200OK, new CurrentUserResponse(
                IsAuthenticated: true,
                UserId: Guid.Parse("7d3e6f0a-2b1c-4d5e-8f9a-0b1c2d3e4f5a"),
                UserName: ExampleUser,
                Roles: [AppRoles.BrandManager],
                BrandIds: [1, 5],
                HomeWarehouseId: null));

        group.MapGet("/antiforgery", Antiforgery)
            .AllowAnonymous()
            .WithName("BffAntiforgery")
            .WithSummary("Returns an antiforgery request token for the current session.")
            .WithDescription(
                "Send requestToken in the header named by headerName (X-XSRF-TOKEN) on every POST, PUT, PATCH and DELETE. "
                + "The token is bound to the user, so fetch a new one after signing in or out. The web app normally "
                + "receives it with the first page and calls this only as a fallback.")
            .WithResponseExample(StatusCodes.Status200OK, new AntiforgeryTokenResponse("CfDJ8…", BffDefaults.AntiforgeryHeaderName));

        return group;
    }

    /// <summary>
    /// Checks the credentials through <see cref="ICredentialVerifier"/> and signs in with exactly the returned claims.
    /// 204 with the cookie on success; every failure, including an invalid body, is the same 400 SS-AUTH-001.
    /// </summary>
    internal static async Task<Results<NoContent, ProblemHttpResult>> LoginAsync(
        LoginRequest request, ICredentialVerifier verifier, TimeProvider time, HttpContext http, CancellationToken cancellationToken)
    {
        if (!(await LoginValidator.ValidateAsync(request, cancellationToken).ConfigureAwait(false)).IsValid)
        {
            return InvalidCredentials();
        }

        var result = await verifier.VerifyAsync(request.UserName, request.Password, http.Connection.RemoteIpAddress, cancellationToken)
            .ConfigureAwait(false);
        if (result.IsFailure)
        {
            return InvalidCredentials();
        }

        var properties = new AuthenticationProperties { IsPersistent = request.RememberMe };
        properties.Items[BffDefaults.SessionIdItem] = Guid.NewGuid().ToString("N");
        properties.Items[BffDefaults.ValidatedAtItem] = time.GetUtcNow().ToString("O", CultureInfo.InvariantCulture);

        await http.SignInAsync(BffDefaults.CookieScheme, BffCookieEvents.CreatePrincipal(result.Value.Claims), properties)
            .ConfigureAwait(false);
        return TypedResults.NoContent();
    }

    internal static async Task<NoContent> LogoutAsync(HttpContext http, ClaimsPrincipal user)
    {
        ArgumentNullException.ThrowIfNull(user);
        await http.SignOutAsync(BffDefaults.CookieScheme).ConfigureAwait(false);
        return TypedResults.NoContent();
    }

    /// <summary>The current user from the claims, without a database call.</summary>
    internal static Ok<CurrentUserResponse> Me(ClaimsPrincipal user)
    {
        if (user.Identity?.IsAuthenticated != true)
        {
            return TypedResults.Ok(CurrentUserResponse.Anonymous);
        }

        return TypedResults.Ok(new CurrentUserResponse(
            IsAuthenticated: true,
            UserId: Guid.TryParse(user.FindFirstValue(AppClaimTypes.Subject), out var id) ? id : null,
            UserName: user.FindFirstValue(AppClaimTypes.Name),
            Roles: [.. user.FindAll(AppClaimTypes.Role).Select(c => c.Value).Order(StringComparer.Ordinal)],
            BrandIds: [.. user.FindAll(AppClaimTypes.Brand).Select(c => ParseShort(c.Value)).OfType<short>().Order()],
            HomeWarehouseId: ParseShort(user.FindFirstValue(AppClaimTypes.Warehouse))));
    }

    /// <summary>A fresh request token for the current principal (fallback; normally it comes with the prerendered page).</summary>
    internal static Ok<AntiforgeryTokenResponse> Antiforgery(IAntiforgery antiforgery, HttpContext http)
    {
        var tokens = antiforgery.GetAndStoreTokens(http);
        return TypedResults.Ok(new AntiforgeryTokenResponse(tokens.RequestToken!, tokens.HeaderName ?? BffDefaults.AntiforgeryHeaderName));
    }

    private static ProblemHttpResult InvalidCredentials() =>
        TypedResults.Problem(
            statusCode: StatusCodes.Status400BadRequest,
            title: "Sign-in failed",
            detail: "The user name or password is incorrect.",
            extensions: new Dictionary<string, object?> { [ProblemDetailsRegistration.CodeKey] = ProblemCodes.InvalidCredentials });

    private static short? ParseShort(string? value) =>
        short.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var parsed) ? parsed : null;
}
