"""Generates .github/workflows/deploy-<service>.yml and deploy-migrations.yml (STAGE_4_PLAN 8.3).

Each workflow's path filter is computed from the project references, so a service redeploys whenever anything it is
built from changes: its host, every project it references (transitively), the shared build files, its module's SQL and
the delivery tooling. Run it after changing project references:

    python tools/generate_deploy_workflows.py

The architecture test DeployWorkflowTests fails if a workflow is out of date or a deployable project is not covered.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKFLOWS = ROOT / ".github" / "workflows"

# Service name -> host project, and the module whose SQL the service's migrations run (None for the gateway).
SERVICES = {
    "gateway": ("src/Bootstrapper/SmartSpare.Gateway/SmartSpare.Gateway.csproj", None),
    "identity": ("src/Bootstrapper/Services/SmartSpare.Services.Identity/SmartSpare.Services.Identity.csproj", "identity"),
    "inventory": ("src/Bootstrapper/Services/SmartSpare.Services.Inventory/SmartSpare.Services.Inventory.csproj", "inventory"),
    "fleet": ("src/Bootstrapper/Services/SmartSpare.Services.Fleet/SmartSpare.Services.Fleet.csproj", "fleet"),
    "procurement": ("src/Bootstrapper/Services/SmartSpare.Services.Procurement/SmartSpare.Services.Procurement.csproj", "procurement"),
    "forecasting": ("src/Bootstrapper/Services/SmartSpare.Services.Forecasting/SmartSpare.Services.Forecasting.csproj", "forecasting"),
    "reporting": ("src/Bootstrapper/Services/SmartSpare.Services.Reporting/SmartSpare.Services.Reporting.csproj", "reporting"),
}
MIGRATIONS = "src/Bootstrapper/SmartSpare.MigrationRunner/SmartSpare.MigrationRunner.csproj"

SHARED = [
    "Directory.Build.props",
    "Directory.Packages.props",
    "global.json",
    "src/Bootstrapper/Directory.Build.props",
    ".github/actions/gates/**",
    "tools/check.sh",
    "tools/build-images.sh",
]


def references(project: pathlib.Path) -> set[pathlib.Path]:
    """The project and every project it references, transitively."""
    seen: set[pathlib.Path] = set()
    stack = [project.resolve()]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        text = current.read_text(encoding="utf-8")
        for include in re.findall(r'<ProjectReference\s+Include="([^"]+)"', text):
            stack.append((current.parent / include.replace("\\", "/")).resolve())
        # Shared props of a folder (ServiceHost.cs, the services' references) count as part of the project.
        for props in current.parent.parents:
            candidate = props / "Directory.Build.props"
            if candidate.exists() and ROOT in candidate.parents:
                for include in re.findall(r'<ProjectReference\s+Include="([^"]+)"', candidate.read_text(encoding="utf-8")):
                    include = include.replace("$(MSBuildThisFileDirectory)", "").replace("\\", "/")
                    stack.append((candidate.parent / include).resolve())
    return seen


def relative(path: pathlib.Path) -> str:
    return path.relative_to(ROOT).as_posix()


def paths_for(project: str, extra: list[str]) -> list[str]:
    folders = {relative(p.parent) + "/**" for p in references(ROOT / project)}
    folder_props = set()
    for p in references(ROOT / project):
        for parent in p.parent.parents:
            if parent == ROOT:
                break
            if (parent / "Directory.Build.props").exists():
                folder_props.add(relative(parent / "Directory.Build.props"))
            if (parent / "ServiceHost.cs").exists():
                folder_props.add(relative(parent / "ServiceHost.cs"))
    return sorted(folders) + sorted(folder_props - set(SHARED)) + SHARED + extra


def render(name: str, title: str, paths: list[str], body: str) -> str:
    lines = "\n".join(f"      - '{p}'" for p in paths)
    return f"""# Generated by tools/generate_deploy_workflows.py; edit the generator, not this file.
name: {title}

# STAGE_4_PLAN 8.3: runs on a push to main that changes anything this deployment is built from. Until the first
# deployment (stage 10, #85) only a manual run deploys: pushes skip the job unless the repository variable
# DEPLOY_ON_PUSH is 'true'.
on:
  push:
    branches: [main]
    paths:
{lines}
  workflow_dispatch:

permissions:
  contents: read
  id-token: write

concurrency:
  group: deploy-{name}
  cancel-in-progress: false

env:
  DOTNET_NOLOGO: true
  DOTNET_CLI_TELEMETRY_OPTOUT: true
  NUGET_PACKAGES: ${{{{ github.workspace }}}}/.nuget/packages

jobs:
  deploy:
    name: Deploy {name}
    if: github.event_name == 'workflow_dispatch' || vars.DEPLOY_ON_PUSH == 'true'
    runs-on: ubuntu-latest
    environment: production
    timeout-minutes: 40

    steps:
      - uses: actions/checkout@v7

      # The same gates as every pull request (#63, #64): nothing is pushed that fails them.
      - uses: ./.github/actions/gates

      # OIDC with a federated credential: no long-lived secret in the repository (ADR 0009).
      - uses: azure/login@v2
        with:
          client-id: ${{{{ vars.AZURE_CLIENT_ID }}}}
          tenant-id: ${{{{ vars.AZURE_TENANT_ID }}}}
          subscription-id: ${{{{ vars.AZURE_SUBSCRIPTION_ID }}}}

      - name: Sign in to the registry
        run: az acr login --name "${{{{ vars.ACR_NAME }}}}"
{body}"""


def service_body(name: str, module: str | None) -> str:
    images = f"{name} migrations" if module else name
    migrate = f"""
      # ADR 0020: the Platform's and this module's migrations, with this commit's runner image, before the new revision.
      - name: Migrate {module}
        run: tools/run-migration-job.sh "${{{{ vars.RESOURCE_GROUP }}}}" "${{{{ vars.ACR_LOGIN_SERVER }}}}/smartspare/migrations:${{{{ github.sha }}}}" --module {module}
""" if module else ""
    return f"""
      - name: Build and push the images
        env:
          TAG: ${{{{ github.sha }}}}
          REGISTRY: ${{{{ vars.ACR_LOGIN_SERVER }}}}
        run: tools/build-images.sh {images}
{migrate}
      - name: Deploy the revision
        run: >-
          az containerapp update --name {name} --resource-group "${{{{ vars.RESOURCE_GROUP }}}}"
          --image "${{{{ vars.ACR_LOGIN_SERVER }}}}/smartspare/{name}:${{{{ github.sha }}}}"

      # Through the gateway, as a user would reach it: every service's readiness, waking it from zero (8.7).
      - name: Smoke test
        run: curl --fail --silent --show-error --max-time 120 "${{{{ vars.GATEWAY_URL }}}}/warmup"
"""


MIGRATIONS_BODY = """
      - name: Build and push the image
        env:
          TAG: ${{ github.sha }}
          REGISTRY: ${{ vars.ACR_LOGIN_SERVER }}
        run: tools/build-images.sh migrations

      # Every context in catalogue order (ADR 0020 §3): the first deployment, and changes to the runner or the Platform.
      - name: Migrate everything
        run: tools/run-migration-job.sh "${{ vars.RESOURCE_GROUP }}" "${{ vars.ACR_LOGIN_SERVER }}/smartspare/migrations:${{ github.sha }}"
"""


def main() -> int:
    check = "--check" in sys.argv
    outputs: dict[pathlib.Path, str] = {}
    for name, (project, module) in SERVICES.items():
        extra = [f"db/sql/{module}/**", "tools/run-migration-job.sh"] if module else []
        extra.append(f".github/workflows/deploy-{name}.yml")
        outputs[WORKFLOWS / f"deploy-{name}.yml"] = render(name, f"Deploy {name}", paths_for(project, extra), service_body(name, module))
    outputs[WORKFLOWS / "deploy-migrations.yml"] = render(
        "migrations", "Deploy migrations",
        [relative((ROOT / MIGRATIONS).parent) + "/**", "src/Bootstrapper/SmartSpare.ModuleCatalog/**", "db/bootstrap/**",
         "db/sql/platform/**", "src/BuildingBlocks/SmartSpare.Infrastructure/Persistence/Platform/**"]
        + SHARED + ["tools/run-migration-job.sh", ".github/workflows/deploy-migrations.yml"],
        MIGRATIONS_BODY)

    stale = []
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.name)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run python tools/generate_deploy_workflows.py)", file=sys.stderr)
        return 1
    print(("up to date: " if check else "wrote: ") + ", ".join(p.name for p in outputs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
