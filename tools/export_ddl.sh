#!/usr/bin/env bash
# Regenerates db/ddl/smartspare_schema.sql from a database built by the migrations.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
{ echo "-- SmartSpare — complete DDL of the database (GENERATED, do not edit)"
  echo "-- Source of truth: db/migrations/V*.sql. Regenerated by tools/export_ddl.sh"
  echo "-- Schema version: $(psql -X -tAc "select max(version) from meta.schema_migration where kind='V'")"
  pg_dump --schema-only "${PGDATABASE:-smartspare}"; } > "$ROOT/db/ddl/smartspare_schema.sql"
echo "written db/ddl/smartspare_schema.sql"
