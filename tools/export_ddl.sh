#!/usr/bin/env bash
# Regenerates db/ddl/smartspare_schema.sql (reference DDL, pg_dump --schema-only) from a database
# built by the EF Core migrations (SmartSpare.MigrationRunner or the AppHost).
# Connects like db/scripts/env.sh: PG* variables win, otherwise .env (smartspare_migrator).
# Needs psql and pg_dump 17 on PATH.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/db/scripts/env.sh"
connect_as_migrator
PSQL=(psql -X -tA -v ON_ERROR_STOP=1)

# Last applied migration of every EF context (one history table per context schema, ADR 0011).
versions=""
for schema in $("${PSQL[@]}" -c "SELECT table_schema FROM information_schema.tables
                                 WHERE table_name = '__ef_migrations_history' ORDER BY table_schema"); do
  last="$("${PSQL[@]}" -c "SELECT max(migration_id) FROM \"$schema\".__ef_migrations_history")"
  versions+="--   $schema: $last"$'\n'
done

{ echo "-- SmartSpare — complete DDL of the database (GENERATED, do not edit)"
  echo "-- Source of truth: the EF Core migrations of each module and their SQL parts in db/sql/."
  echo "-- Regenerated by tools/export_ddl.sh from a database built by SmartSpare.MigrationRunner."
  echo "-- Last migration per context (history schema: migration):"
  printf '%s' "$versions"
  # \restrict / \unrestrict carry a random key per dump; dropped so regenerating is reproducible.
  pg_dump --schema-only "${PGDATABASE:-smartspare}" | grep -vE '^\\(un)?restrict '; } \
  > "$ROOT/db/ddl/smartspare_schema.sql"
echo "written db/ddl/smartspare_schema.sql"
